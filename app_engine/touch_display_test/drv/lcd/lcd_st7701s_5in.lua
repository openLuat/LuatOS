--- ic_init 回调：供 lcd_display_rgb 使用，返回 custom_cmds 表
-- lcd_display_rgb 调用后将 custom_cmds 传给 display.init
-- @param table params  引脚参数（此版本不需要，命令序列固定）
-- @return table  custom_cmds 命令序列
function M.ic_init(params)
    return M.custom_cmds
end

--[[
独立初始化: 一次 display.init 完成 RGB + IC 初始化
用于不经过 lcd_display_rgb 的场景

display.init 内部流程:
  1. 通过 pin_cs/pin_scl/pin_sdi 建立 SPI 通道
  2. 发送 custom_cmds 中的 IC 寄存器序列
  3. 初始化 RGB 接口（时序参数）
  4. 分配 FrameBuffer
]]
function M.init(params)
    local r = display.init("custom", {
        id        = 0,
        interface = "rgb",
        w         = params.w or 480,
        h         = params.h or 854,
        -- RGB 时序
        hbp       = params.hbp or 30,
        hspw      = params.hspw or 6,
        hfp       = params.hfp or 12,
        vbp       = params.vbp or 30,
        vspw      = params.vspw or 1,
        vfp       = params.vfp or 12,
        pclk_hz   = params.bus_speed or (30 * 1000 * 1000),
        -- 引脚
        pin_rst   = params.pin_rst or 9,
        pin_cs    = params.pin_cs or 2,
        pin_scl   = params.pin_clk or 23,
        pin_sdi   = params.pin_sda or 22,
        -- IC 初始化命令
        custom_cmds = M.custom_cmds,
    })
    log.info("st7701s", "display.init", r)
    if r then
        local addr, fb_size, fb_count = display.getFbInfo()
        log.info("st7701s", "getFbInfo", addr, fb_size, fb_count)
    end
    return r
end

return M
