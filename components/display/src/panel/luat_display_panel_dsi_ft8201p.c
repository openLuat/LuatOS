/*DSI面板时序参数（1200x1920@60Hz，4 lane）：
  pclk = MPLL 1.8GHz / 11 = 163.6MHz，TH = 1200+80+60+15 = 1355，
  TV = 1920+35+25+15 = 1995，刷新 = 163.6e6 / (1355*1995) = 60.5Hz。
  用 non-burst 视频模式，链路速率 = pclk * 24 / lanes = 982Mbps（不含 burst 余量），
  避免 burst 模式下 1.5 倍余量把速率顶到 1473Mbps 超出 DPHY 能力 */
