--[[
@module  gb28181_config
@summary GB28181 demo 的集中配置
@version 1.0
@date    2026.10.15
@usage
本文件只放"会因现场而变"的东西：平台地址、设备国标编码、通道表、视频源、音频参数、功能开关。
一份配置同时被 gb28181_app.lua 和 video_source.lua 使用。

平台参数按**合宙视频物联网大数据平台**(video.luatos.com)填写；接入其它 GB28181
平台时，直接改第零节的 6 个 SIP 参数和第一节的设备编码。

本文件没有对外接口，在其他功能模块中 require "gb28181_config" 即可。
]]

local M = {}

--=============================================================================
-- 零、平台参数(SIP 服务器)
--=============================================================================

--[[
特别注意平台页面上的两个骗人的字段：
  「设备用户/设备密码」是设备调平台 **HTTP 接口**用的，**不是 SIP 摘要凭据**。
  SIP 摘要密码在「流媒体服务器 → 主机节点 → SIP服务器密码」里(对应下面的 PASSWORD)。
  拿「设备用户/设备密码」去注册，平台会回 403 wrong password。
]]

-- 官方文档《GB28181 接入平台 V1.0.0》给的是该平台的非洲部署
-- (102.217.166.120)；本部署换成 video.luatos.com，域与端口不变。
M.SERVER_ADDR = "video.luatos.com"
-- 平台侧 SIP 端口。**5060 是设备自己的端口，不是平台的**(文档里大华/海康
-- 两栏的"设备 SIP 端口"都写 5060)，别拿去当服务器端口。
M.SERVER_PORT = 8116
-- 从 401 的 `WWW-Authenticate: Digest realm="3702010049"` 读回，与文档一致，不必猜
M.DOMAIN      = "3702010049"
-- 域 + "20" + 8 位序号
M.SERVER_ID   = "37020100492000000001"
-- 「流媒体服务器 → 主机节点」里的 **SIP服务器密码**(平台前端字段名 registerPassword)，
-- 与 sipServerId/sipDomain/sipServerIp/sipServerPort 同一组。
-- 实测「设备密码」(ccic112233445566)、「设备用户」(admin) 两套组合都回
-- 403 wrong password，换回这个值立刻 200 OK。
M.PASSWORD    = "12345678"
-- **必须 TCP**：8116 的 UDP 静默(5060 则 UDP/TCP 全无应答，防火墙丢包)。
-- 走 TCP 还有个好处：设备在 NAT 后，平台回 INVITE 只能顺着这条已建立的连接进来。
M.TRANSPORT   = "tcp"

--=============================================================================
-- 零·一、与平台无关的行为开关
--=============================================================================

--[[
网卡选择："4g" = 板载 4G（socket.LWIP_GP）；"eth" = SPI 外挂 CH390H（socket.LWIP_ETH）。
4G 下设备在运营商 NAT 后面，平台主动发起的 INVITE 只能顺着**设备先连出去**的
TCP 信令进来，所以 4G 用 TRANSPORT="tcp"（上面的默认值）。
]]
M.NETDRV = "4g"      -- "4g" | "eth"

-- 打印原始 SIP 收包（前 160 字节）。排查平台畸形报文时临时打开
M.DEBUG_SIP = false

--=============================================================================
-- 一、本设备参数
--=============================================================================

-- 平台设备编辑页的「接入ID」。**平台上要先有这台设备**(网页上建好，编码一致)
M.DEVICE_ID   = "35020000001320000001"
-- 平台上这台设备是**录像机**(类型编码 132)，通道按国标编码成它下面的摄像机(131)。
-- 若平台按"IPC 自报一个通道"的口径收，把这一行改成与 DEVICE_ID 相同。
M.CHANNEL_ID  = "35020000001310000001"
M.CHANNEL_NAME = "hefei001"
-- 平台设备页的「设备端口」
M.LOCAL_PORT  = 5060
-- 设备发起的广播会话先按 UDP offer；实际承载以平台应答的 m= 为准，
-- 平台回 TCP 时 client 会把 transport 交给音频引擎（无需重建流）。
M.AUDIO_OFFER_TCP = false

-- 心跳周期(秒)：视频物联网平台对 10s 高频心跳应答不稳定；60s 足够保活。
-- 组件判活窗口按 `keepalive + 15s` 动态计算，见 exgb28181client 的 sip_task。
M.KEEPALIVE = 60

-- 注册有效期(秒)，平台到期前设备会自动续注册
M.EXPIRES = 3600

--=============================================================================
-- 二、媒体端口
--=============================================================================

-- 点播(视频/RTP)本地端口池起点，占用 [30000, 30000+max_sessions)
M.RTP_PORT_BASE = 30000

-- 对讲(音频)本地端口池起点。**必须和上面这段错开**：两个池子撞在一起时，
-- 端口被上一通占着，外部音频引擎(voip)绑不上会静默换端口，
-- 而 SDP 里报给平台的还是旧端口 —— 平台下行全丢且两侧都不报错
M.AUDIO_PORT = 31000

--=============================================================================
-- 三、通道表(Catalog)
--=============================================================================

-- [[没有通道记录时平台取不到"来源 id"，点播的 INVITE 会被一律拒绝]] —— 所以这张表是必须的
-- 通道编码(CHANNEL_ID)与通道名(CHANNEL_NAME)见第一节；
-- 平台就是靠 Catalog 里这个条目让用户在界面上点播的
M.CHANNELS = {
    {
        device_id    = M.CHANNEL_ID,
        name         = M.CHANNEL_NAME,    -- 界面上显示的通道名
        manufacturer = "LuatOS",
        model        = "Air780EHV",
        owner        = "LuatOS",
        civil_code   = M.DOMAIN,
        address      = "test",
        parent_id    = M.DEVICE_ID,
        status       = "ON",
    },
}

--=============================================================================
-- 四、视频源
--=============================================================================

-- 780EHV 没有摄像头接口，所以点播推的是本地放的一个 H.264 裸流(annex-b)。
-- Luatools 下载脚本时把 demo.h264 一起放进 /luadb/ 即可(test.h264 也行)。
-- 文件不存在时 demo 不会挂：自动改用"拒绝视频点播"(回 488)，
-- 信令/目录/对讲照常 —— 收下却发不出流会让平台那次点播永远不完成
M.VIDEO_PATH = "/luadb/demo.h264"

-- 推流节拍与循环策略放在 video_source.lua 里，见那边的 push_loop 说明
M.ENABLE_VIDEO = true


--=============================================================================
-- 五、语音对讲(可选)
--=============================================================================

-- 对讲依赖固件里的音频通路（voip / gb28181.stream / 芯片后端）。
-- 关掉时 demo 依然会应答平台的 Broadcast 通知，只是不出声/不上行。
M.ENABLE_TALK = true

--[[
传给 exgb28181audio.start(sess, opts) 的参数（Air780EHV 内置 ES8311，PA 硬件常开）：
  volume —— 软件音量 0~1000
  aec    —— AEC/降噪/AGC 开关
]]
M.AUDIO_OPTS = {
    volume   = 80,     -- 软件音量 0~1000
    -- 若固件没有编入 LUAT_USE_VOIP_AEC（SpeexDSP），voip.start 会以
    -- "AEC requested but SpeexDSP is not enabled" 直接失败，此时必须为 false；
    -- 固件支持 AEC 后可改回 true。
    aec      = false,
}

--[[
codec 电源脚，默认 20（Air780EHV 内置 ES8311 的供电控制脚，
官方 demo 的 dac_ctrl 都是 20）。

本 demo 在启动时自己拉高这个脚，不给音频框架控制：由框架来回拉放会导致
ES8311 掉电，现象是 I2C 报 137/143/140 或 ver=0x0。
]]
M.AUDIO_CODEC_PWR_PIN = 20
M.AUDIO_CODEC_POWER_LEVEL = 1      -- 高有效
M.AUDIO_CODEC_READY_MS    = 200    -- 上电后等多久芯片才可用

-- ES8311 挂在哪个 I2C（官方 Air780EHV 的 demo 都是 i2c_id = 0，走 I2C0）
M.AUDIO_CODEC_I2C_ID = 0

-- 初始化 codec 时把 I2S 开在哪个采样率。**必须和对讲采样率一致（8k）**：
-- 这个时钟"先到先得"，开错了后面 voip 改不动 → 输出 2 倍速 → 没声音。
M.AUDIO_CODEC_I2S_SAMPLE = 8000

-- 不要改成借 exaudio.setup 初始化 ES8311：它会激活旧框架，而旧框架写 I2S
-- 时钟是无条件的，audio_v2 改不动，结果对讲 2 倍速、每帧静音。

-- ES8311 的 MCLK 倍频：MCLK = 采样率 × 这个值。
-- 256 有双重依据：C 侧 `#define MCLK_DIV_FRE 256`、Lua 表里有 {2048000, 8000, ...}。
M.AUDIO_CODEC_MCLK_DIV = 256

-- I2S 通讯格式。ES8311 用标准 I2S（"i2s"）。
--
--[[
可选值："i2s"（**标准飞利浦 I2S，当前**） | "lsb" | "msb"

三种在 SDK 里的实际差别（am_usp.c:1042-1057）：
    I2S_MODE_I2S: dataDly=1, bclkPolarity=0     ← 标准 I2S
    I2S_MODE_LSB: dataDly=1, bclkPolarity=1
    I2S_MODE_MSB: dataDly=0, bclkPolarity=1

**要和 codec 侧对齐才有声音**：
  · ES8311（EHV）：`es8311.set_format()` 把 reg0x09/0x0A 的格式位清成 00
    = 标准 I2S ⇒ 这里用 "i2s"。官方 audio_v2 的 ES8311 例子正是
    `set_format()` + `CFG_VALUE_I2S_MODE_I2S`。
]]
M.AUDIO_I2S_MODE = "i2s"           -- "i2s" | "lsb" | "msb"

--[[
声道与位宽。**这两个不能省**。

驱动注册时的默认 `channel_type = LUAT_I2S_CHANNEL_STEREO`，
而 8kHz 单声道的流被当成立体声交错 ⇒ **输出 2 倍速** ⇒ 抖动缓冲喂不上 ⇒
没声音 + `jb resync` 反复刷屏。所以每次起音频前都显式设置。
]]
M.AUDIO_I2S_CHANNEL    = "right"   -- "right"（单声道走右声道，同 i2s.MONO_R） | "left"
M.AUDIO_I2S_FRAME_BITS = 16        -- 16bit 数据 / 16bit 槽

-- 不要再加"按档位轮换扫频"的调试开关：三个轴（对齐/声道/位宽）在 ES8311
-- 上已有官方参照物。要试新参数就改上面三个 M.AUDIO_I2S_*，一次只改一个。

--=============================================================================
-- 六、时间同步
--=============================================================================

-- 国标设备的时间戳(注册/目录/录像)要对得上平台，跑 NTP 是标准做法。
-- 只跑信令+点播不依赖它，所以同步失败不阻塞启动。网线场景下很便宜，建议留着。
-- 服务器用固件内置的那组(ntp.aliyun.com)；要换服务器得传 IP，接口是 socket.sntp(ip)
M.ENABLE_NTP = true

-- 状态打印周期(毫秒)，方便看注册/会话/收发的实时情况
M.STAT_MS = 10000

return M
