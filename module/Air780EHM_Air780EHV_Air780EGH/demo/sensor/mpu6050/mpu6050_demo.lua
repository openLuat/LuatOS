@author  王城钧
@usage
=== 演示流程: 基础测试(10项) → 持续读取(10秒) → DMP测试(可选) ===

本文件通过 exs_mpu6050 扩展库的 API 逐一演示 MPU6050 的以下功能：

1.  I2C 初始化与芯片自检      -- i2c.setup + mpu.init, 自动检测地址 0x68/0x69, 自动校准
2.  芯片温度读取              -- mpu.get_temp(), 单位 ℃
3.  三轴加速度读取            -- mpu.get_accel(), 单位 g, 静止水平时 Z≈1.0g
4.  三轴角速度读取            -- mpu.get_gyro(), 单位 °/s, 静止时应接近 0
5.  静态倾角测量              -- mpu.get_tilt(), 通过加速度计直接推算俯仰/横滚角
6.  碰撞/敲击检测             -- mpu.detect_tap(阈值, 去抖时间), 检测瞬时加速度冲击
7.  自由落体/失重检测         -- mpu.detect_freefall(阈值), 三轴合加速度低于阈值时触发
8.  校准状态查询              -- mpu.is_calibrated(), 检查加速度/陀螺零偏是否已校准
9.  手动重新校准(注释)        -- mpu.calibrate(), 设备需水平静止, 200次采样取平均
10. 持续读取(加速度+互补滤波+碰撞) -- 循环 10 秒, 演示 get_attitude() 动态姿态融合

附加: DMP 数字运动处理器     -- mpu.dmp_init() + mpu.dmp_get_euler(), 需 dmp_firmware.lua
]]

-- 加载 exs_mpu6050 扩展库
-- 该库提供 MPU6050 的全部驱动功能: 初始化/校准/数据读取/姿态解算/DMP
local mpu = require "exs_mpu6050"

-- 硬件 I2C 总线 ID
-- Air780EGH: 使用 I2C1 (Pin66=SDA, Pin67=SCL) → hwid=1
-- Air8000:   使用 I2C0 (GPIO2=SDA, GPIO1=SCL)   → hwid=0
local i2c_hwid = 1

----------------------------------------------------------------
-- 基础功能测试 (10 项, 顺序执行)
-- 覆盖: 初始化 → 温度 → 加速度 → 陀螺仪 → 倾角 → 碰撞 → 失重 → 校准 → 持续读取
----------------------------------------------------------------
local function mpu6050_task()

    ------------------------------------------------------------
    -- [1/10] 初始化 I2C + MPU6050
    -- - i2c.setup 配置 I2C 总线为快速模式(400kHz)
    -- - mpu.init 自动检测芯片地址(先试0x68, 再试0x69), 验证 WHO_AM_I 寄存器(应为0x68)
    -- - 首次上电会自动触发校准: 设备需水平静止, 采样200次, 需要50次以上有效静止采样
    -- - 校准数据会保存到文件 /mpu6050_calib.txt, 后续启动自动加载
    ------------------------------------------------------------
    log.info("TEST", "=== [1/10] 初始化 ===")
    i2c.setup(i2c_hwid, i2c.FAST)

    if not mpu.init(i2c_hwid) then
        log.error("TEST", "初始化失败! 检查接线: VCC=3.3V GND SCL SDA")
        while true do sys.wait(1000) end
    end

    ------------------------------------------------------------
    -- [2/10] 芯片温度读取
    -- - MPU6050 内置温度传感器, 用于内部补偿陀螺零漂
    -- - 正常工作时芯片温度约 30~45℃, 随运行时间缓慢上升
    ------------------------------------------------------------
    log.info("TEST", "=== [2/10] 温度 ===")
    local temp = mpu.get_temp()
    log.info("TEST", string.format("芯片温度: %.1f°C", temp))

    ------------------------------------------------------------
    -- [3/10] 三轴加速度读取 (已校准)
    -- - 返回 x, y, z 分量, 单位 g (1g ≈ 9.8m/s² 重力加速度)
    -- - 静止水平放置时: Z≈+1.0g, X≈0g, Y≈0g
    -- - Z 轴正向为芯片顶面朝上, X/Y 向由芯片丝印方向决定
    -- - 量程默认 ±2g, 分辨率 16384 LSB/g
    ------------------------------------------------------------
    log.info("TEST", "=== [3/10] 加速度 (单位g) ===")
    local a = mpu.get_accel()
    log.info("TEST", string.format("accel  x=%.3f  y=%.3f  z=%.3f", a.x, a.y, a.z))
    -- 如果 Z 轴偏差超过 0.15g, 提示检查放置或校准
    if math.abs(a.z - 1.0) > 0.15 then
        log.warn("TEST", "Z轴偏差较大(期望≈1.0g), 检查传感器是否水平")
    end

    ------------------------------------------------------------
    -- [4/10] 三轴角速度读取 (已校准)
    -- - 返回 x, y, z 分量, 单位 °/s (度每秒)
    -- - 静止时应全部接近 0, 超过 ±5°/s 说明零偏校准不佳
    -- - 量程默认 ±250°/s, 分辨率 131 LSB/(°/s)
    ------------------------------------------------------------
    log.info("TEST", "=== [4/10] 陀螺仪 (单位°/s) ===")
    local g = mpu.get_gyro()
    log.info("TEST", string.format("gyro   x=%.1f  y=%.1f  z=%.1f", g.x, g.y, g.z))
    if math.abs(g.x) > 5 or math.abs(g.y) > 5 or math.abs(g.z) > 5 then
        log.warn("TEST", "陀螺零偏较大(期望≈0), 重新校准试试")
    end

    ------------------------------------------------------------
    -- [5/10] 静态倾角读取 (加速度计直接推算)
    -- - pitch(俯仰): 设备前后倾斜角度, 前倾为正
    -- - roll(横滚):  设备左右倾斜角度, 右倾为正
    -- - 纯加速度推算, 静态精度高(受重力矢量影响)
    -- - 动态时受运动加速度干扰, 噪声大, 不宜用于运动中的姿态估计
    ------------------------------------------------------------
    log.info("TEST", "=== [5/10] 倾角 (单位°) ===")
    local pitch, roll = mpu.get_tilt()
    log.info("TEST", string.format("tilt   pitch=%.1f°  roll=%.1f°", pitch, roll))

    ------------------------------------------------------------
    -- [6/10] 碰撞/敲击检测
    -- - detect_tap(threshold, debounce_ms)
    --   threshold:  加速度合矢量阈值(g), 默认 2.0g, 轻敲可设 1.5g
    --   debounce_ms: 去抖时间(ms), 默认 500ms, 防止单次敲击被多次触发
    -- - 原理: 三轴加速度模长 sqrt(x²+y²+z²) 超过阈值则触发
    -- - 静止时模长约 1.0g, 敲击瞬间可达 3~5g
    ------------------------------------------------------------
    log.info("TEST", "=== [6/10] 碰撞检测 ===")
    if mpu.detect_tap(2.0) then
        log.info("TEST", "碰撞检测: YES")
    else
        log.info("TEST", "碰撞检测: NO (正常, 静止时不应触发)")
    end

    ------------------------------------------------------------
    -- [7/10] 自由落体/失重检测
    -- - detect_freefall(threshold)
    --   threshold: 加速度合矢量阈值(g), 默认 0.3g
    -- - 原理: 三轴合加速度 < 阈值时判定为失重/自由落体
    -- - 自由落体时加速度趋近于 0, 正常静止时为 1.0g
    ------------------------------------------------------------
    log.info("TEST", "=== [7/10] 自由落体检测 ===")
    if mpu.detect_freefall() then
        log.info("TEST", "自由落体: YES (你在自由落体?)")
    else
        log.info("TEST", "自由落体: NO (正常)")
    end

    ------------------------------------------------------------
    -- [8/10] 校准状态查询
    -- - is_calibrated() 返回校准数据是否就绪
    -- - 校准数据来自: 首次自动校准 或 手动 calibrate() 调用
    -- - 数据保存在 /mpu6050_calib.txt (6个值: gx,gy,gz,ax,ay,az)
    -- - 无校准时 get_accel/get_gyro 返回原始值, 精度降低
    ------------------------------------------------------------
    log.info("TEST", "=== [8/10] 校准状态 ===")
    log.info("TEST", "已校准:", mpu.is_calibrated())

    ------------------------------------------------------------
    -- [9/10] 手动重新校准 (默认注释)
    -- - 在运行过程中需要重新校准时取消注释
    -- - 调用前确保设备水平静止, 否则校准结果不准确
    -- - 校准完成会自动覆盖 /mpu6050_calib.txt
    ------------------------------------------------------------
    -- log.info("TEST", "=== [9/10] 手动校准 ===")
    -- local ok = mpu.calibrate()
    -- log.info("TEST", "校准结果:", ok)

    ------------------------------------------------------------
    -- [10/10] 持续读取 (10秒循环)
    -- - 每 200ms 读取一次: 加速度 + 互补滤波姿态 + 碰撞检测
    -- - get_attitude() 使用互补滤波: alpha=0.96
    --   陀螺积分权重 96% + 加速度推算权重 4%
    --   陀螺积分提供高频动态响应, 加速度修正低频漂移
    -- - 必须持续循环调用以保持积分连续性, 中断后积分重置
    -- - 在循环中同时监控碰撞事件并累计次数
    ------------------------------------------------------------
    log.info("TEST", "=== [10/10] 持续读取 (10秒) ===")
    local start = os.clock()
    local tap_count = 0
    while os.clock() - start < 10 do
        local a = mpu.get_accel()
        local p, r = mpu.get_attitude()
        if mpu.detect_tap(2.0, 500) then
            tap_count = tap_count + 1
            log.info("TEST", string.format("碰撞! 第%d次", tap_count))
        end
        log.info("TEST", string.format(
            "a:(%5.2f,%5.2f,%5.2f)g  p=%.1f° r=%.1f°",
            a.x, a.y, a.z, p, r))
        sys.wait(200)
    end
    log.info("TEST", string.format("持续读取完成, 碰撞%d次", tap_count))

    ------------------------------------------------------------
    -- 基础测试完毕
    ------------------------------------------------------------
    log.info("TEST", "========== 所有测试完成 ==========")
end


----------------------------------------------------------------
-- DMP 数字运动处理器测试 (可选)
-- - DMP 是 MPU6050 内置的运动处理引擎, 直接输出融合后的四元数/欧拉角
-- - 相比互补滤波, DMP 精度更高、CPU 负载更低
-- - 前提: 需要 dmp_firmware.lua 固件文件 (将 DMP 固件数组转为 Lua table)
--   固件来源: GitHub i2cdevlib → Arduino/MPU6050/MPU6050_6Axis_MotionApps20.h
--   将 dmpMemory[3062] 数组复制为 Lua 格式: return {0x00, 0x01, ...}
-- - DMP 输出: Roll(横滚), Pitch(俯仰), Yaw(偏航, 无磁力计会漂移)
----------------------------------------------------------------
local function mpu6050_dmp()
    sys.wait(3000)  -- 等待基础测试开始后再启动 DMP
    if mpu.dmp_init() then
        log.info("DMP_TEST", "DMP 就绪")
        while true do
            local r, p, y = mpu.dmp_get_euler()
            if r then
                log.info("DMP", string.format("R:%.1f P:%.1f Y:%.1f", r, p, y))
            end
            sys.wait(3000)
        end
    end
end

-- 启动基础测试任务 (协程运行, 通过命名函数指定)
sys.taskInit(mpu6050_task)

-- 启动 DMP 测试任务 (可选, 无 dmp_firmware.lua 时 dmp_init 会返回 false)
sys.taskInit(mpu6050_dmp)
