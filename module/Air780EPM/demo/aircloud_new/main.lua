--[[
@module  main
@summary excloud 云平台通信示例工程入口
@version 1.0.0
@date    2026.08.29
@author  LuatOS 嵌入式软件设计开发
@usage
本文件为示例工程入口，职责如下：
1. 声明工程名称与版本号（PROJECT / VERSION）
2. 通过 require 统一加载各业务模块（模块内部自行通过 sys.taskInit 启动各自协程任务）
3. 调用 sys.run() 启动 LuatOS 事件循环

被加载的模块与职责：
    netdrv_device  —— 网络驱动设备（网卡选择与配置）
    config         —— 全局业务配置（传输协议、心跳、上报周期、运维日志等）
    excloud_main   —— excloud 服务核心（setup/on/open/心跳/状态/事件分发）
    excloud_cmd    —— 服务器控制命令解析与执行
    excloud_report —— 业务数据上报
    excloud_upload —— 文件上传（图片/音频/运维日志）

运行前提：
- 目标模组：4G 蜂窝模组（excloud 会自动识别设备类型为 1）
- 网络：4G 数据卡已就绪（默认网卡）
- excloud.lua 扩展库需与工程一同打包（位于工程根目录）
]]

-- =========================================================================
-- 工程信息
-- =========================================================================
PROJECT = "excloud_demo"
VERSION = "001.999.000"

-- =========================================================================
-- 统一 require 加载所有业务模块
-- 各模块在自身文件内通过 sys.taskInit 启动各自的协程任务，
-- 因此此处只需 require 加载即可，无需额外调用。
-- =========================================================================
require("netdrv_device")   -- 网络驱动设备：按配置加载网卡驱动（默认 4G）
require("config")          -- 全局业务配置
require("excloud_main")    -- excloud 云平台服务核心（连接/认证/心跳/事件）
require("excloud_cmd")     -- 服务器控制命令解析与执行
require("excloud_report")  -- 业务数据上报
require("excloud_upload")  -- 文件上传（图片/音频/运维日志）

-- =========================================================================
-- 启动 LuatOS 系统事件循环
-- sys.run() 会不断轮询底层消息并分发给各协程任务，程序不会返回。
-- =========================================================================
sys.run()
