--[[
@module  ws2812_fonts
@summary WS2812 演示使用的字模数据与文本条带构建（中文 22×22 / 英文 22×11 / ASCII 5×7）
@version 1.0
@date    2026.08.17
@usage
适用产品：合宙 Air1780P / Air1780H / Air1780HV。
         字模尺寸与灯板 22×22 强绑定，灯板尺寸非 22×22 时需重新生成字模。

本模块由 ws2812_scroll_task 调用，提供：
  WS2812_FONT5x7      5×7 ASCII 小字模（列优先，bit0=顶行），放大 2× 后渲染
  WS2812_FONT_CN      中文 22×22 字模（欢迎使用），行优先字符串
  WS2812_FONT_EN22    英文半宽 22×11 大字模（LuatOS），行优先字符串
  ws2812_build_strip(text)  将 UTF-8 文本打包为列掩码数组
最终输出"列掩码数组" columns：每个元素是一个 22-bit 整数，
第 y 位为 1 表示该列第 y 行的 LED 点亮。scroll_task 按列偏移遍历即可渲染。
]]

