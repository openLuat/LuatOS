--[[
@module  netlight
@summary 网络指示灯控制模块（GPIO25，开机常亮）
@version 1.0
@date    2026.10.23
@usage
Air8603 / Air8605 开发板的网络指示灯接在 GPIO25，高电平点亮、低电平熄灭。
本模块在加载时即点亮指示灯并保持常亮，不随网络状态闪烁。

使用示例：
local netlight = require("netlight")
netlight.on()   -- 点亮（常亮）
netlight.off()  -- 熄灭
]]

--============================================================
-- 模块常量
--============================================================

local NETLIGHT_GPIO = 25           -- 网络指示灯 GPIO 编号
local LEVEL_ON = 1                 -- 高电平点亮
local LEVEL_OFF = 0                -- 低电平熄灭

--============================================================
-- 公开接口
--============================================================

local M = {}

-- 点亮指示灯并保持常亮
function M.on()
    gpio.setup(NETLIGHT_GPIO, LEVEL_ON)
    log.info("netlight", "网络指示灯常亮")
end

-- 熄灭指示灯
function M.off()
    gpio.setup(NETLIGHT_GPIO, LEVEL_OFF)
    log.info("netlight", "网络指示灯熄灭")
end

--============================================================
-- 模块加载时执行：开机常亮
--============================================================

M.on()

--============================================================
-- 模块导出
--============================================================

return M
