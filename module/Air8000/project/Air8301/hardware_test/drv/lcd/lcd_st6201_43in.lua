-- MADCTL(0x36) 值：方向 0/1/2/3 对应 0x00/0xA0/0xC0/0x60（与参考工程一致）
local madctl = {0x00, 0xA0, 0xC0, 0x60}

--[[
LCD 初始化协程（require 后自动启动）：
@local
@function lcd_init_task
]]
local function lcd_init_task()
    -- direction=0：框架不做旋转，旋转/镜像完全由自定义 MADCTL（0x36=0x00）控制
    local direction = 0

    local result = lcd.init("custom", {
        port            = lcd.HWID_0,
        w               = 480,
        h               = 272,
        pin_rst         = 36,
        direction       = direction,
        bus_speed       = 80 * 1000 * 1000,
        sleepcmd        = 0x10,
        wakecmd         = 0x11,
        interface_mode  = lcd.WIRE_4_BIT_8_INTERFACE_I,
        rb_swap         = true,
    })
    log.info("lcd_st6201", "lcd.init result:", result)
    if not result then
        log.error("lcd_st6201", "lcd.init 失败")
        return
    end

    -- 厂商初始化寄存器序列（0xFF=0xA5 解锁扩展命令 + GIP 时序 + 正负 Gamma）
    for _, item in ipairs(init_regs) do
        lcd.cmd(item[1], string.char(item[2]))
    end

    -- MADCTL: direction=0 → 0x00（正常 480×272 排列，与参考工程显示方向一致）
    lcd.cmd(0x36, string.char(madctl[direction + 1]))

    -- 设置显示窗口 480×272
    lcd.cmd(0x2A, string.char(0x00, 0x00, 0x01, 0xDF)) -- CASET: 列 0~479
    lcd.cmd(0x2B, string.char(0x00, 0x00, 0x01, 0x0F)) -- RASET: 行 0~271

    -- 退出扩展命令模式
    lcd.cmd(0xFF, string.char(0x00))

    -- Sleep Out 退出休眠
    lcd.cmd(0x11); sys.wait(120)

    -- 开启显示
    lcd.cmd(0x29); sys.wait(20)

    -- 结束自定义初始化
    lcd.user_done()

    -- 清屏
    lcd.clear()

    -- 初始化 AirUI 渲染引擎 + 内置字库
    local w, h = lcd.getSize()
    if airui.init(w, h) then
        airui.font_load({
            type = "hzfont",
            size = 20,
            cache_size = 1024,
            antialias = 1,
        })
    else
        log.error("lcd_st6201", "airui.init 失败")
    end
    _G.screen_w = 480
    _G.screen_h = 272

    -- 背光开启回调：收到 BACKLIGHT_ON 消息后点亮 PWM0
    local function backlight_on_cb()
        pwm.start(0)
    end

    -- 注册背光（仅配置，不开启；收到 BACKLIGHT_ON 消息后点亮）
    pwm.setup(0, 1000, 100)
    sys.subscribe("BACKLIGHT_ON", backlight_on_cb)

    -- 通知其它模块：LCD/AirUI 已就绪（TP 初始化、首页打开依赖此消息）
    sys.publish("DISPLAY_READY")
    log.info("lcd_st6201", "初始化完成")
end

sys.taskInit(lcd_init_task)
