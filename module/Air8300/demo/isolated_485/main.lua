本 demo 演示的核心功能为：
1、将 Air8300 的隔离 485 接口（UART1）配置为串口应答模式
2、串口板（USB 转 485）发送数据给工控板，工控板收到一帧后回复固定内容

硬件说明（Air8300 双网口双 485 工控板）：
1、隔离 485 固定接 UART1，收发方向由 GPIO37（物理 PIN28）控制；
   PIN28 上电默认是 LCD 功能，必须先 pins.setup 重映射，否则方向脚无效，
   表现为只能接收、不能发送
2、485 芯片供电脚为 GPIO29（物理 PIN18），必须拉高，否则收发器不工作、
   总线没有偏置，串口初始化虽然成功，但一个字节都收不到
3、接线：板子 A 接串口板 A，板子 B 接串口板 B，隔离侧 GND 与串口板 GND 共地；
   板上 3.3V/5V 供电开关需打开，AGND/SEL/VISO 开关拨至 AGND

注意事项：
1、485 的管脚复用、串口初始化、数据接收与应答逻辑都在 rs485_reply.lua 中
2、该示例程序不依赖扩展库，使用内核固件自带的核心库即可

更多说明参考本目录下的 readme.md 文件；
