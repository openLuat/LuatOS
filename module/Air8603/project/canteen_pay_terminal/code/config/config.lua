-- ==================== 6. 饭卡二维码 → 账户键 ====================
-- 虚构示例（仅演示格式，不是任何真实工牌数据）：
--   badge9000000000000001-DEMO0001
--   ├─ 横杠前：badge9000000000000001（工牌 ID，可能随发卡时间变化）
--   └─ 横杠后：DEMO0001（★「识别有效位数」，稳定，对应员工表 number 字段）
--
-- parse_rule 决定从二维码里取哪一段作为「账户键」：
--   "after_dash"         取最后一个横杠之后（★ 示例默认，按接口约定）
--   "before_dash"        取最后一个横杠之前（含前缀）
--   "before_dash_digits" 取横杠之前的纯数字（旧兜底用）
--   "digits"             取整串纯数字
--   "raw" / ""           原样使用，并退回下面的 mode 规则
-- take_n 决定「有效位数」：0=全部，正数=取前 N 位，负数=取后 N 位。
--   例：若规定横杠后只认前 8 位 → parse_rule="after_dash", take_n=8
--
-- mode 是旧版兜底规则（parse_rule 为 raw 时生效）：
--   ""       : 二维码内容整体作为卡 ID
--   "digits" : 只保留数字
--   其他     : 当作 Lua 匹配模式，取第一个捕获组，例如 "id=(%%d+)"
--
-- 注意：账户键直接作为员工表 number 字段的查询值，查到的 nametext 用于记消费；
-- 不再需要 account_map 逐人登记。演示模式（C.pay.enable=false）不查余额、不记消费，任何码都能通过。
C.card = {
    mode       = "",
    min_len    = 1,
    parse_rule = "after_dash",   -- ★【必改 E09】← 按现场卡码格式选规则
    take_n     = 0,              -- ★【必改 E09】← 只认前/后 N 位时改这里
}

return C
