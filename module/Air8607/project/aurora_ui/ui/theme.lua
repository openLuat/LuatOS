=== 为什么单独抽一个文件 ===
整屏所有颜色、坐标、字号都从这里取，改风格只需改这一个文件；
各视图模块里不再出现魔法数字。UI Store 的 7 个 demo 都是把色值
散落在 ui.lua 各处（Beverage 的色带、FactoryTwin 的故障灯都各写一份），
一旦要改主题就得全仓搜索，这里从工程结构上避免。

=== 坐标体系（Air8607 + 10 寸 RGB 1024x600）===
  HUD  顶栏      y   0 ..  76   品牌 / 时钟 / 实时性能
  CONTENT 舞台   y  76 .. 514   984 宽的可视区，内部再切成 HERO + PANEL
  DOCK 导航栏    y 522 .. 586   4 个页签 + 滑动手势指示器
  舞台内部：
    HERO  x  24 .. 652  (628 宽)  每个页面左侧的主视觉（全屏 shape）
    PANEL x 664 .. 1000 (336 宽)  右侧 3 张玻璃卡片
]]

local M = {}

-- ==================== 配色 ====================
-- 极光色系：深空底 + 青绿/紫红互补，全部靠亮度与透明度分层，
-- 不用任何图片素材（UI Store 的 demo 几乎都靠 jpg/png 撑场面）。
M.c = {
    bg       = 0x04060D,   -- 全屏底色
    deep     = 0x070B16,   -- 卡片外底色
    panel    = 0x0C1424,   -- 玻璃卡片底
    panel_hl = 0x16233C,   -- 玻璃卡片高光层
    line     = 0x1E2F4D,   -- 细描边 / 网格
    line2    = 0x2A4270,   -- 亮一档的描边

    cyan     = 0x22E6FF,
    aqua     = 0x2BFFD0,
    violet   = 0xA855F7,
    magenta  = 0xFF3D9A,
    blue     = 0x3B82F6,
    amber    = 0xFFB020,
    green    = 0x2BE59B,
    red      = 0xFF4D6D,

    txt      = 0xDCE7F7,   -- 主文字
    dim      = 0x7C8DA6,   -- 次要文字
    dim2     = 0x4A5A75,   -- 极弱文字 / 刻度
    ink      = 0x04121C,   -- 亮底上的文字
}

-- 玻璃卡片的不透明度（0-255；越小越透，能看见背后的极光）
M.o = {
    card    = 210,
    card_hl = 120,
    edge    = 150,
    top_edge = 200,
}

-- ==================== 屏幕与布局 ====================
M.screen = { w = 1024, h = 600 }

M.hud   = { x = 0,   y = 0,   w = 1024, h = 76 }
--[[舞台容器就是页面滑动的裁剪窗口
页面切换时两个页面容器在里面左右平移，靠这个容器的裁剪保证
页面内容不会溢到 HUD / DOCK 上去（LVGL 默认把子对象裁到父边界内）。]]
M.stage = { x = 16,  y = 76,  w = 992, h = 438 }
M.hero  = { x = 8,   y = 8,   w = 628, h = 422 }   -- 相对舞台
M.panel = { x = 648, y = 8,   w = 336, h = 422 }   -- 相对舞台

M.dock  = { x = 16,  y = 524, w = 992, h = 62 }
M.tabs  = { n = 4, x = 18, y = 7, w = 226, h = 48, gap = 12 }  -- 相对 dock

M.card  = { w = 336, h = 130, gap = 16 }           -- PANEL 内 3 张卡

-- ==================== 字号 ====================
-- hzfont 是矢量字库，12-255 任意字号，这里只登记实际用到的档位
M.f = {
    h1     = 26,   -- 品牌主标题
    hero   = 44,   -- 主视觉大数字
    value  = 30,   -- 卡片数值
    title  = 18,   -- 卡片标题
    body   = 15,
    sub    = 13,
    mini   = 12,
}

-- ==================== 帧率预算 ====================
--[[为什么是 30ms 而不是 33ms
LVGL 自身的画面刷新周期由固件常量控制（AIRUI_REFRESH_PERIOD_MS，约 33ms）。
主循环如果也取 33ms，两者完全同频会产生拍频：周期性出现"这个刷新周期里
没等到新数据"的顿挫。取 30ms 略快一点即可错开。
真机吃不消时把 frame_ms 调成 40（25fps）或 50（20fps）——
所有动画都按 dt 推进，改帧率只影响流畅度，不影响动作速度。
]]
M.perf = {
    frame_ms  = 30,   -- 主循环目标节拍（ms）
    bg_every  = 3,    -- 每 3 帧才重算一次极光背景（≈10fps，省 2/3 面积刷新）
    hud_ms    = 250,  -- HUD 文字刷新间隔（每帧 set_text 会反复重排文本）
}

return M
