}
M.c = c

M.screen = { w = 1024, h = 600 }

-- ==================== 布局 ====================
M.hud = { h = 64 }

-- 反应堆（左列主视觉）
M.reactor = { cx = 162, cy = 246, R = 118 }

-- PAT 按键：2x2
M.pat = { x = 24, y = 388, w = 130, h = 48, gap = 16 }

-- 音序器网格
M.grid = {
    x = 320, y = 76,          -- 区域左上
    label_w = 96,             -- 轨名列宽（含静音热区）
    cell_w = 32, cell_h = 26,
    gap = 4,
    row_h = 36,
    cols = 16, rows = 8,
}
-- 步进格起点 x = grid.x + label_w + 8 = 424，16*32 + 15*4 = 572，到 x=996 收边

-- 示波器卡
M.scope = { x = 320, y = 384, w = 680, h = 116 }

-- 底部控制条
M.bottom = { y = 512, h = 80 }

-- ==================== 字体 ====================
M.f = {
    huge = 64,   -- 反应堆中心 BPM 数字
    big  = 30,   -- 标题（与 main.lua 载入的字号表一致：11/13/16/22/30/64）
    val  = 22,   -- 按键文字
    body = 16,
    sub  = 13,
    mini = 11,
}

-- ==================== 性能预算 ====================
M.perf = {
    frame_ms = 30,   -- 主循环节拍（30ms 避开 LVGL 33ms 刷新拍频，同 moto_dash）
    scope_ms = 50,   -- 示波器 20Hz（波形线段多，降频省图元）
    hud_ms   = 250,  -- HUD 文字 4Hz
}

-- ==================== 轨道定义 ====================
--[[
name 纯 ASCII + 短横线（hzfont 缺字兜底）；
gain 是该轨混音增益（0..1），bass 响度大，压一点防削顶。
]]
M.tracks = {
    { id = "KICK",  name = "KICK",  color = c.cyan,    gain = 1.00 },
    { id = "SNARE", name = "SNARE", color = c.magenta, gain = 0.85 },
    { id = "CLAP",  name = "CLAP",  color = c.violet,  gain = 0.80 },
    { id = "HATC",  name = "HAT-C", color = c.lime,    gain = 0.55 },
    { id = "HATO",  name = "HAT-O", color = c.amber,   gain = 0.55 },
    { id = "TOM",   name = "TOM",   color = c.blue,    gain = 0.85 },
    { id = "RIM",   name = "RIM",   color = 0xFF7AC8,  gain = 0.65 },
    { id = "BASS",  name = "BASS",  color = c.green,   gain = 0.75 },
}

