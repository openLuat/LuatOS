    room_wet = 0.18,  -- "房间"湿声：短反馈回声垫在击打之间，鼓组连成一片不发干
    room_fb  = 0.30,  -- 回声反馈量（每圈更弱）
    room_lp  = 0.32,  -- 回声路径一阶低通：重复声逐圈变闷，模拟空气吸收
    auto_play = true, -- 上电自检后直接开嗨（真机演示用，量产可关）
}

