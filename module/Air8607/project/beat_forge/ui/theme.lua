    dim2     = 0x3D465C,   -- 极弱文字 / 网格暗格
    txt      = 0xEDF2FF,   -- 主文字

    cyan     = 0x22E6FF,   -- 强调 1（引擎 / 播放头）
    magenta  = 0xFF3D9A,   -- 强调 2（节拍脉冲）
    violet   = 0xA855F7,
    lime     = 0xB6FF3C,
    amber    = 0xFFB020,
    blue     = 0x4C8DFF,
    green    = 0x2BE59B,
