--[[
@module  theme
@summary BEAT FORGE - 节拍熔炉设计令牌（配色 / 布局 / 轨道 / 图案 / 节拍预算）
@version 1.0
@date    2026.10.22
@author  江访

=== 设计取向 ===
硬件是"音视频大屏板"，所以这台 APP 走的是舞台设备的视觉语言：
近黑底 + 双霓虹强调（青 0x22E6FF / 品红 0xFF3D9A）+ 等分网格。
界面里最亮的东西永远是"当前正在发声的东西"——步进格点亮、反应堆脉冲、
示波器波形都跟着同一台采样时钟走，声音和画面同源。

=== 坐标体系（1024x600）===
  顶栏 HUD    y   0 .. 58    标题 / BPM / SWING / VOL 三个滑块 / FPS
  左列        x  24 .. 300   反应堆（圆心 162,246 半径 118）+ PAT A-D 两行
  音序器      x 320 .. 996   y 76 .. 364  轨名列 96 + 16 步 x 32（间隔 4）
  示波器卡    x 320 .. 1000  y 384 .. 500  实际输出 PCM 波形 + 轨道能量
  底部控制条  y 512 .. 592   PLAY/STOP / FILL / CLEAR / MUTE / 提示

=== 字体注意 ===
hzfont 里没有中间点（·）、度数（°）、乘号（×）这类符号，用了显示方框。
界面文本只用 ASCII + 汉字 + 斜杠，节拍写 "1/16"、单位写 "BPM"。
]]

local M = {}

-- ==================== 配色 ====================
local c = {
    bg       = 0x06070C,   -- 全屏底色
    panel    = 0x0E1119,   -- 卡片底
    panel_hl = 0x151A26,   -- 卡片高光层
    line     = 0x232A3A,   -- 描边
    line2    = 0x323C52,   -- 亮描边
