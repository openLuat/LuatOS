--[[
@module  theme
@summary INDUS BOARD - 工业产线看板设计令牌（配色 / 布局 / 字号 / 视图 / 刷新预算）
@version 1.0
@date    2026.10.23
@author  江访

=== 设计取向 ===
这台 APP 是"工业产线 / 设备看板"，要回答的问题是
「车间那一屏：哪条线在跑、哪台机要修、今天出了多少、费了多少电」。
所以视觉按工业大屏的不等分栏走：主视觉大、辅助块小，不摆均匀卡片阵。
颜色只用来编码语义（状态灯 / 告警等级 / 负载高低 / 良好与缺陷），
不做纯装饰的渐变；最亮的东西永远是"正在变化的那个数"，静态结构压到 dim2 以下。

=== 坐标体系（1024x600）===
  顶栏 HUD   y   0 .. 58    标题 | 视图名 + 说明 | FPS / 图元数 / 时钟
  舞台外框   x  12 .. 1012  y  62 .. 514   1000 x 452
  舞台内容   x  15 .. 1009  y  65 .. 511   994 x 446（clip_corner）
  底部切换栏 y 522 .. 588    三个视图按钮 + 自动轮播开关

=== 视图内部约定 ===
每个视图自带一张不等分栏 rect 表（写在 bd_*.lua 的 M.rects），
坐标一律是**舞台内容区相对坐标** 0..994 x 0..446，
不是屏幕绝对坐标（写 T.inner.x + ... 会整体偏移 (15, 65)），
也不是舞台外框相对坐标。
分块底与描边用 airui.container 画（静态、不进图元预算），
动态图元才写进 shape 图元池。

=== 字体注意 ===
hzfont 里没有中间点（·）、度数（°）、乘号（×）、约等于（±/Ω/μ）这类符号，
用了会显示方框。界面文本只用 ASCII + 汉字 + 斜杠：
温度写 "C"、电压写 "V"、流量写 "m3/h"、频率写 "Hz"、百分号直接 "%"
]]

