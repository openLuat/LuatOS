=== 设计取向 ===
这台看板的卖点是"把车间画成一屏能看进去的三维场景"，分三层：
  1、背景层：**纯矢量**渐变天空 + 地平线光带 + 远景厂房线框（一次性画好，永不刷新）；
  2、地面层：用 airui.shape 按透视相机实时算出来的网格、光柱、流光、热点环；
  3、空中层：玻璃面板 + 大字读数（左 3 张 / 右 3 张，不遮住中央场景）。
"像 3D" 靠的不是贴图，而是**所有三维元素共用同一个相机**：
网格、光柱、厂房剪影走同一个 project()，灭点 / 近大远小 / 亮度衰减因此自洽。

=== 为什么不用照片底图（重要）===
真机（Air1603 + RGB 直刷）上 1024x600 的照片 PNG 解码需要 **2.4MB 连续内存**
（lodepng 输出 ARGB8888），LVGL 堆空闲 6MB 但被碎片化后拿不到这么大的连续块：
  decode fail: lodepng_decode32 err=83 (memory allocation failed)
更糟的是解码失败不会被缓存，LVGL 每次重绘 image 都会重新 open → 每次 369ms，
帧率直接被钉死在 1~2fps（HUD 上 fps=2，日志里刷 refresh retry）。
所以真机路径一律走矢量背景；T.use_photo 只是 PC 上想对比原图效果时的开关。

=== 坐标体系（1024x600）===
  顶栏 HUD    y   0 .. 52    标题 | 视图名 + 说明 | FPS / 图元 / 时钟
  左栏面板    x  10 .. 282   OEE / 产量 / 设备状态
  中央场景    x 290 .. 734   3D 底图 + 全息叠加层（热点锚点写在中栏坐标里）
  右栏面板    x 742 .. 1024  能耗 / 温度振动 / 告警
  底部切换栏  y 542 .. 592    三个视图 + 滚动字幕

=== 字体注意 ===
hzfont 没有中间点（·）、度数（°）、乘号（×）、约等于（±/Ω/μ），用了显示方框。
界面文本只用 ASCII + 汉字 + 斜杠，单位写成 "C" "kWh" "pcs" "mm/s"。
]]

