-- ==================== 3D 相机 ====================
--[[
相机沿 +z 看，世界坐标：x 向右、y 向上（地面 y=0）、z 向前。
地面网格、光柱、热点环全部走同一个 project()，
改一个参数整页透视一起变——这就是"自洽"的来源。

调参口径（1024x600）：
  eye_h    相机离地高度（越大俯视越陡）
  dist     相机到原点的距离（越大透视越弱）
  pitch    俯角（弧度），≈ atan(eye_h / dist) 时地平线正好落在 CY
  focal    焦距（像素），越大越"长焦"、近大远小越不明显
  cx / cy  屏幕主点：cy 就是地平线高度
]]
M.cam = {
    eye_h = 3.0,
    dist  = 8.0,
    pitch = math.atan(3.0 / 8.0),   -- 视轴正好指向世界原点：原点落在 (cx, cy)
    focal = 700,
    cx    = 512,
    cy    = 292,
}

