--[[素材路径解析
真机：脚本与图片平铺在 /luadb 下（tools/project_download 下载后按 RST）。
PC 模拟器：脚本目录被挂成根 "/"，图片其实在脚本同级，所以补一个根路径兜底。
缺图只告警不抛错——底图缺失时整页退化成纯色，其余功能照常。]]
function M.asset(name)
    local p = M.img.dir .. name
    local ok, has = pcall(io.exists, p)
    if ok and has then return p end
    local p2 = "/" .. name
    ok, has = pcall(io.exists, p2)
    if ok and has then return p2 end
    log.warn("theme", "缺少素材", p)
    return p
end

