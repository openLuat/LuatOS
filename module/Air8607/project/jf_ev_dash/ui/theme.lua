=== 设计取向 ===
纯电车型的仪表语言是"深色底 + 电光青 + 弧"：
  底色压到近纯黑（夜间行车不刺眼），信息分层只靠一个强调色，
  强调色跟随驾驶模式变化（节能青绿 / 标准电光青 / 运动品红）。
主表盘不放实体指针，改由"弧形进度 + 弧头光点"表达车速
—— 指针是燃油车的语言，弧形光带才是电驱的语言。

=== 坐标体系（1024x600）===
  顶栏      y    0 .. 56     转向灯 / 灯光 / READY / 时钟 / 车外温度
  左列卡片  x   24 .. 256    电量环（y 72..280）、里程（y 294..530）
  右列卡片  x  768 .. 1000   功率环（y 72..280）、电耗趋势（y 294..530）
  主表盘    圆心 (512,296)  外径 234，速度弧半径 210 带宽 22，扫角 135°~405°（270°）
  底部      y  546 .. 588    三个驾驶模式按键

=== 字体注意 ===
hzfont 里没有中间点（·）、度数（°）这类符号，用了会显示方框。
本工程界面文本只用 ASCII + 汉字 + 斜杠，单位写成 "km/h" "C" "kWh/100km"。
]]

