--[[性能参数
真机 1024x600 RGB 屏没有 GPU，屏幕级重绘一次就是 61 万像素，
所以"每帧重画多少面积"比"每秒画多少帧"更要紧：
  - 动态层只覆盖表盘（472x472），不再整屏失效；
  - 中心辉光 / 红区 / 呼吸外环都放静态层，只画一次；
  - 顶栏指示灯单独两个小图层，只在状态变化时重画。
剩下真正每帧都要重画的只有速度弧本身，而且是整段一条 arc（不做分块）。
arc 图元的绘制区域永远是"圆心 ± r"的整圆方框（内部再用角度掩膜裁），
所以每帧的固定成本就是这一个整圆掩膜 —— quality 是在真机上把它换掉的旋钮。]]
M.perf = {
    --[[主循环节拍：airui 的显示刷新周期 AIRUI_REFRESH_PERIOD_MS 就是 33ms，
    节拍比它快只会多产生一次"合并掉"的失效，白跑一遍脚本逻辑，所以对齐 33。]]
    frame_ms = 33,
    card_ms  = 100,  -- 卡片刷新间隔（10Hz）
    --[[画质档位（速度弧永远是整段一条 arc，档位只影响周围的效果）
    2 = 两条旋转装饰弧 + 弧头光晕（PC / 性能充裕的真机）
    1 = 去掉旋转装饰弧，保留弧头光晕
    0 = 再省掉弧头光晕，只留一颗实心亮点]]
    quality  = 2,
    auto     = true, -- 按实测帧率自动降档（只降不升，避免来回抖）
    slow_fps = 20,   -- 低于这个帧率就降一档
}

return M
