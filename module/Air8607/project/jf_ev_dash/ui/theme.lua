    txt      = 0xE9F1FA,   -- 主文字

    eco      = 0x21F3A6,   -- 节能：青绿
    normal   = 0x2FD4FF,   -- 标准：电光青
    sport    = 0xFF4D6D,   -- 运动：品红
    amber    = 0xFFC53D,   -- 电量
    violet   = 0xA97BFF,   -- 电耗 / 装饰弧
    red      = 0xFF3B57,   -- 红区 / 报警
    green    = 0x46F08A,   -- 转向灯 / 能量回收
    blue     = 0x5C9BFF,   -- 远光
