M.c = c

M.screen = { w = 1024, h = 600 }

--[[主表盘几何
半径层级（由外向内）：
  234 外框细环 / 228 次细环 / 221 速度弧外沿 / 210 速度弧中心线 / 199 速度弧内沿
  196..180 刻度 / 166 数字 / 150 与 138 旋转装饰弧 / 120 以内留给车速数字
几何必须满足 cy + R < 530（底部模式键上方）且 cx ± R ⊂ (256, 768)（左右卡片之间）：
  296 + 234 = 530、512 ± 234 = 278..746，两边各留 22px。
]]
M.dial = {
    cx = 512, cy = 296,
    R  = 234,        -- 最外圈细环半径
    Ra = 210,        -- 速度弧中心线半径
    Rw = 22,         -- 速度弧带宽
    a0 = 135, a1 = 405,
    vmax = 180,      -- 表底 180 km/h
    vred = 150,      -- 红区起点
    major = 20,      -- 大刻度间隔（带数字）
    minor = 5,       -- 小刻度间隔
    --[[两条旋转装饰弧的半径：故意放在"速度弧外沿 221"与"外框 228"之间的窄环带里，
    不压刻度数字、也不压中心车速（早期放在 150/138 会横穿刻度数字，像划痕）。]]
    deco_r = { 225, 231 },
}

M.cards = {
    a = { x = 24,  y = 72,  w = 232, h = 208 },   -- 电量
    b = { x = 24,  y = 294, w = 232, h = 236 },   -- 里程
    c = { x = 768, y = 72,  w = 232, h = 208 },   -- 功率
    d = { x = 768, y = 294, w = 232, h = 236 },   -- 电耗趋势
}

--[[卡片内的小环（电量 / 功率）
半径 42、带宽 10，画在 84x84 的方框里；圆心由卡片决定，
左卡环在左边、右卡环在右边，形成镜像对称。]]
M.ring = {
    r = 42, w = 10,
    a0 = 135, a1 = 405,     -- 与主表盘同一套扫角，视觉语言统一
    lx = 58, ly = 86,       -- 左卡环心（相对卡片）
    rx = 174, ry = 86,      -- 右卡环心（相对卡片）
}

