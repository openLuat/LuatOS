-- ==================== 节拍 ====================
--[[园区大屏不需要 30fps：
  - 告警点位脉冲要顺一点 -> 每帧（约 16fps）
  - 卡片进度环/条形 -> 500ms
  - 文字 -> 500ms 且只在数值变化时写
这样每帧真正重绘的只有三个 44x44 的脉冲点位。]]
