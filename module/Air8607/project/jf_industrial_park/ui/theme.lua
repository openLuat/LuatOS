=== 设计取向 ===
园区管理系统是"值班室大屏"：信息密度高，但必须有明确的视觉层级 ——
  1、底色压到近纯黑，长时间盯不刺眼；
  2、只用一个强调色（电光青）表达"主数据"，其余信息用亮度分层；
  3、状态色（正常青绿 / 警告暖黄 / 异常红 / 提示蓝紫）只出现在真正需要判断的地方；
  4、所有卡片同一套圆角、描边、标题格式（竖条 + 中文 + 英文小字），
     让 7 个模块看起来是一套系统，而不是七张图拼起来。

=== 版式（1024x600，8px 栅格）===
  顶栏      y    0 .. 56
  左列      x   24 .. 256   园区总览(R1) y 64..296 / 能耗监测(R2) y 308..528
  中列      x  276 .. 748   园区态势地图 y 64..400 / 三张服务小卡 y 412..528
  右列      x  768 .. 1000  实时告警 y 64..300 / 安防通行 y 312..528
  底栏      y  544 .. 584

=== 字体注意 ===
hzfont 没有中间点（·）、度数（°）这类符号；本工程只用 ASCII + 汉字，
单位写成 "C" "dB" "%" "kWh"，分隔用空格或斜杠。
]]

