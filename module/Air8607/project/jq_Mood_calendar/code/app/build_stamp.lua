--[[
@module  build_stamp
@summary 烧录时间戳（由 tools/更新烧录时间.bat 自动重写，不要手改）
@author  蒋骞
@version 1.0
@date    2026.10.30

=== 为什么需要它 ===
本机没有 4G / 没有 WiFi，也没法和烧录工具通信，脚本自己不可能知道「现在几点」。
能拿到的两个时间线索都有缺陷：
  RTC          —— 断电后是 1970 之类的无效值
  rtos.buildDate() —— 是「固件」的编译日期，合宙官方固件往往是几个月前编的

所以这里放一个「烧录戳」：烧录前跑一次 tools/更新烧录时间.bat，
它会把当前电脑时间原样写到下面这行。上电时 rtc_util 优先用它校准 RTC，
做到「什么时候烧录，情绪日历的今天就是哪天」。

没跑过 bat 时 stamp = nil，自动退回固件编译日期（不如这个准，但聊胜于无）。
]]

return {
    -- 形如 "2026-10-30 14:05:00"，由 tools/更新烧录时间.bat 写入
    stamp = "2026-10-30 16:58:33",
}
