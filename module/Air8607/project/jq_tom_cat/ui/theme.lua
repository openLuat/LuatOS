--[[
@module  theme
@summary 汤姆猫 TOM CAT - 设计令牌（配色 / 布局 / 字号 / 帧率预算 / 音色参数）
@version 1.0
@date    2026.10.25
@author  江访

=== 设计取向 ===
卡通插画风，不用任何图片素材：猫的每一根线条都由 airui.shape 的
line / circle / ellipse / rect 图元程序化画出来（椭圆实心填充由 C 层逐行
扫描，耳朵这种三角面用 Lua 侧扫描线填充，见 fx.pool）。

配色取"暖阳客厅 + 蓝灰毛色"：背景奶油暖色，猫是蓝灰短毛、粉肉垫，
强调色用粉（交互反馈）与蓝（信息文本），和屏幕的 1024x600 横向比例配合。

=== 坐标体系（1024x600）===
  左侧信息面板  x  36 .. 392   y  42 .. 558
  猫舞台        x 418 .. 1016  y   6 .. 594   （动态层 shape 的范围）
  猫本体        以 x=660 为中轴：头顶 y=60，脚底 y=584，尾巴尖到 x≈950

左面板与猫身体完全不重叠，触摸命中测试因此不需要处理遮挡（见 ui_main）。

=== 字体 ===
hzfont 里没有中间点（·）、问号全角等符号，界面文本只用 ASCII 与汉字。
字号只允许 f 表里这几个值，app_main 会按同一张表一次性载入。
]]
local M = {}

-- ==================== 配色 ====================
local c = {
    -- 场景
    bg        = 0xFBE7CE,   -- 全屏底色（暖奶油）
    bg_halo   = 0xFFF3DF,   -- 猫背后的柔光
    floor     = 0xEFD3AE,   -- 地板
    wall_dot  = 0xF6D9B6,   -- 墙面装饰点
    shadow    = 0x8A6B47,   -- 猫的落地影

    -- 猫
    fur       = 0xA9B3C6,   -- 主毛色（蓝灰）
    fur_dark  = 0x8794AC,   -- 深色（条纹 / 尾尖）
    fur_light = 0xC6CEDA,   -- 浅色（前爪）
    belly     = 0xEFF3F9,   -- 肚皮
    muzzle    = 0xF8FAFD,   -- 口鼻区
    ear_in    = 0xF3A9B7,   -- 耳内
    nose      = 0xEF8E9F,   -- 鼻头
    pad       = 0xF2BFC8,   -- 肉垫
    mouth     = 0x7B2B3A,   -- 口腔
    tongue    = 0xF0808F,   -- 舌头
    iris      = 0x5FBF74,   -- 瞳色
    pupil     = 0x1B2430,   -- 瞳孔
    white     = 0xFFFFFF,
    outline   = 0x3A4459,   -- 描边（卡通黑）

    -- 面板
    panel     = 0xFFFDF7,
    panel_brd = 0xE8D3B4,
    text      = 0x3E4A66,
    text_sub  = 0x7C879E,
    accent    = 0xE9718C,   -- 强调 1（交互 / 粒子）
    accent2   = 0x5A9BD8,   -- 强调 2（信息）
}
M.c = c

M.screen = { w = 1024, h = 600 }

-- ==================== 布局 ====================
-- 左侧信息面板
M.panel = { x = 36, y = 42, w = 356, h = 516 }

-- 动态层（前爪 / 尾巴 / 眨眼 / 嘴巴 / 粒子）的绘制区域。
-- 收窄到猫的活动范围，等于把每帧的无效区从 1024x600 缩到 598x588。
M.stage = { x = 418, y = 6, w = 598, h = 588 }

-- 说话气泡：放在猫头右上方那块空墙面上（放正上方会压住两只耳朵）。
-- 宽度按"6 个汉字 @32 号"留的，台词超过 6 字就会溢出。
M.bubble = { x = 760, y = 10, w = 240, h = 56 }

-- ==================== 字号 ====================
-- app_main 按这张表载入 hzfont，界面里只允许用这些值
M.fonts = { 14, 18, 24, 32, 44 }
M.f = {
    title  = 32,   -- 面板标题
    body   = 18,   -- 面板正文
    small  = 14,   -- 底部小字 / FPS
    bubble = 32,   -- 说话气泡
    btn    = 24,   -- 按钮文字
}

-- ==================== 性能预算 ====================
M.perf = {
    -- 主循环节拍。触摸时会立刻插一帧（见 ui_main.on_touch），所以这个值只决定
    -- 动画的平滑度；20ms 目标 50fps，真机 sys.wait 粒度 10ms 时实际约 30~40fps
    frame_ms   = 20,
    idle_every = 2,   -- 空闲时动态层隔帧重算（尾巴摆动 ≈15fps，省一半全层重绘）
    hud_ms     = 500, -- 状态文字刷新间隔
}

-- ==================== 语音参数 ====================
-- 走本地 TTS（exaudio.play_start type=1），音量只有一个总音量可用
M.audio = {
    model       = "dac", -- Air8607：芯片内置 DAC + HT6873 功放
    vol         = 40,   -- 0..100，之前 85 太吵，40 大约是"桌面玩具"的音量
    priority    = 200,  -- 播放优先级：越高越容易顶掉正在播的那句（TTS 路径用）
    pa_ctrl     = 73,   -- 功放使能 AUDIOPA_EN = GPIO73，高电平开
    pa_on_level = 1,
    dac_delay   = 6,    -- DAC 启动前冗余时间

    -- WAV 兜底路径（固件无 TTS 时用）：资源是 16kHz/16bit/单声道
    rate        = 16000,
    block       = 512,  -- 单块采样数：512 = 32ms，越小越跟手（别低于 256）
}

return M
