--[[
@module  theme
@summary UAV GCS - 设计令牌（配色 / 布局 / 字号 / 页面清单）
@version 1.0
@date    2026.11.02

=== 设计取向 ===
地面站是"夜里盯着看很久"的界面，所以：深空蓝黑底 + 单一青蓝强调色 + 大字号数字。
告警色只在真的出现异常时出现（自稳变红、链路断变橙），平时全屏只有青蓝一种彩色，
这样人眼扫一眼就知道有没有事。

=== 坐标体系（1024x600）===
  顶栏      y   0 ..  52   站名 / 模式 / 链路 / 卫星 / 电压 / 电池 / 时钟
  内容区    y  52 .. 548   五个页面共用，页面内坐标一律相对内容区（0..496）
  标签栏    y 548 .. 600   姿态 / 数据 / 参数 / 功能 / 地图
  标签      x 122 起，宽 148，间隔 10，高 44

=== 字体注意 ===
hzfont 里没有度数（°）、中间点（·）、正负号（±）、约等于（≈），用了会显示方框。
本工程界面文本只用 ASCII + 汉字 + 斜杠：
  角度写 "12.4"（不带单位）、温度写 "42 C"、电压写 "16.4 V"、速度写 "5.2 m/s"。
app_main.lua 会按 font_sizes 逐个 font_load，漏载的字号会回退成方框或错误字形。
]]
local M = {}

-- ==================== 配色 ====================
local c = {
    bg      = 0x05080F,   -- 全屏底色
    panel   = 0x0B1220,   -- 卡片底
    panel2  = 0x0F1828,   -- 卡片高光层 / 次级底
    line    = 0x1B2940,   -- 描边
    line2   = 0x2A3D58,   -- 亮描边
    dim     = 0x7C8DA8,   -- 次要文字
    dim2    = 0x41546F,   -- 极弱文字 / 刻度
    txt     = 0xE6F2FF,   -- 主文字

    cyan    = 0x2FE3FF,   -- 强调：在线 / 正常
    blue    = 0x3E8BFF,   -- 数据：俯仰
    green   = 0x2BE38A,   -- 正常 / 航迹
    amber   = 0xFFB020,   -- 注意
    red     = 0xFF4D5E,   -- 告警 / 自稳
    violet  = 0xA46BFF,   -- 横滚 / 前桨
    pink    = 0xFF6FC0,   -- 后桨

    sky     = 0x1C57B8,   -- 地平仪天
    sky_lo  = 0x3E8BFF,   -- 地平仪天（近地平线）
    gnd     = 0x8A6526,   -- 地平仪地（近地平线）
    gnd_lo  = 0x5A4016,   -- 地平仪地（底部）
}
M.c = c

M.screen = { w = 1024, h = 600 }
M.top    = { h = 52 }
M.content = { y = 52, h = 496 }
M.tabs   = { y = 552, h = 44, w = 148, gap = 10 }

--[[触摸状态常量：某些固件版本的 airui 表里没导出 TP_DOWN，
直接拿 nil 比较会让"整个界面点不动"，所以这里做兜底。
C 层枚举：NONE=0 DOWN=1 HOLD=2 UP=3]]
M.TP_DOWN = (airui and airui.TP_DOWN) or 1
M.TP_HOLD = (airui and airui.TP_HOLD) or 2
M.TP_UP   = (airui and airui.TP_UP) or 3

-- ==================== 字号 ====================
--[[只保留界面真用到的 6 档：hzfont 是逐字号载入的，
每多一档就多一份字形缓存，64 号字在本工程里没有用到，别白占内存。]]
M.f = {
    big  = 40,   -- 卡片主数值
    num  = 28,   -- 中等数值
    mid  = 22,   -- 小标题 / 按钮标题
    body = 18,   -- 正文
    sub  = 15,   -- 次要
    mini = 12,   -- 标签 / 单位
}
M.font_sizes = { 12, 15, 18, 22, 28, 40 }

-- ==================== 刷新预算 ====================
M.perf = {
    frame_ms = 30,    -- 主循环节拍（30ms 避开 LVGL 33ms 刷新拍频）
    slow_ms  = 100,   -- 数据/参数/功能/地图页 10Hz
    text_ms  = 500,   -- 顶栏 2Hz
    idle_sec = 8,     -- 无操作多久开始自动演示
}

-- ==================== 页面 ====================
-- en 只放 3~5 个字符：标签宽 148，左边中文占掉 20~100，右边只留得下这么宽
M.pages = {
    { id = "att",   name = "姿态", en = "ATT" },
    { id = "data",  name = "数据", en = "DATA" },
    { id = "param", name = "参数", en = "PID" },
    { id = "func",  name = "功能", en = "ACT" },
    { id = "map",   name = "地图", en = "MAP" },
}

-- ==================== 姿态页 ====================
--[[3D 视图 590x404：线框房间的地面网格底边落在 y=396 附近，
-- 所以相机中心放在 (305, 262)、焦距 420、视距 6 —— 见 model3d.lua 的推导。]]
--[[相机参数是算出来的，不是试出来的：
把房间 8 个角代进 model3d 的投影公式，得到包围盒 x 65..545 / y 117..366，
正好落在 590x404 的视图里，且留出了顶部 100px 给标题与坐标读数。]]
M.att = {
    view   = { x = 10,  y = 8,   w = 590, h = 404 },
    cam    = { cx = 295, cy = 232, f = 600, d = 9.0, y0 = 0.55 },
    btn    = { x = 10,  y = 420, w = 143, h = 56, gap = 6 },
    panel  = { x = 612, y = 8,   w = 404, h = 290 },
    -- 以下坐标都相对 panel 左上角
    ball   = { cx = 202, cy = 154, r = 86, ring = 100 },
    tape_l = { x = 14,  y = 58, w = 56, h = 192 },
    tape_r = { x = 334, y = 58, w = 56, h = 192 },
    read_y = 304,
    telem  = { y = 364, row = 54, gap = 4 },
}

-- ==================== 数据页 ====================
M.data = {
    x = 12, y = 8, w = 328, h = 232, gap = 8,
}

-- ==================== 参数页 ====================
M.param = {
    list  = { x = 12,  y = 8,   w = 640, h = 472 },
    chart = { x = 660, y = 8,   w = 352, h = 290 },
    info  = { x = 660, y = 306, w = 352, h = 174 },
    row_y = 52, row_h = 48, row_n = 8,
}

-- ==================== 功能页 ====================
--[[八个键排 2 列 x 4 行，行高必须是 (462 - 3*12)/4 ≈ 106：
早先按 146 排，四行加起来 620，下面两行直接掉到标签栏上。]]
M.func = {
    btn  = { x = 12, y = 8, w = 312, h = 106, gap_x = 12, gap_y = 12 },
    log  = { x = 660, y = 8, w = 352, h = 462 },
}

-- ==================== 地图页 ====================
M.map = {
    view = { x = 12,  y = 8, w = 700, h = 472 },
    side = { x = 720, y = 8, w = 292, h = 472 },
    scale = 2.2,      -- 像素 / 米
}

return M
