local M = {}

-- 逐条替换，键是 UTF-8 原字符，值是兼容写法
local SANITIZE = {
    ["\226\128\148"] = "-",    -- — 长破折号
    ["\226\132\131"] = "度",   -- ℃ 摄氏度
    ["\194\183"]     = " ",    -- · 中间点
    ["\239\188\136"] = "(",    -- （
    ["\239\188\137"] = ")",    -- ）
    ["\239\188\139"] = ";",    -- ；
}

local function clean(s)
    if type(s) ~= "string" then return s end
    for k, v in pairs(SANITIZE) do
        if s:find(k, 1, true) then s = s:gsub(k, v) end
    end
    return s
end

-- [[菜名, 菜谱要点], ...] -> { {name=, tip=}, ... }
local function mk(list)
    local out = {}
    for i = 1, #list do
        out[i] = { name = clean(list[i][1]), tip = clean(list[i][2]) }
    end
    return out
end

