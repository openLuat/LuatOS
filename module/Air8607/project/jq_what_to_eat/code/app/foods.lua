-- 条数不符时在启动日志里立刻报警，避免数据文件被改动后界面静默错位
function M.check()
    local s = M.stats
    local ok = true
    if s.diet ~= 50 then
        ok = false
        log.error("foods", "减脂餐应为 50 条，实际", s.diet)
    end
    if s.meat ~= 40 or s.veg ~= 30 or s.soup ~= 10 then
        ok = false
        log.error("foods", "家常菜应为 40/30/10，实际", s.meat, s.veg, s.soup)
    end
    if s.takeout ~= 50 then
        ok = false
        log.error("foods", "外卖应为 50 条，实际", s.takeout)
    end
    if ok then
        log.info("foods", "菜品数据就绪",
            "减脂餐" .. s.diet, "家常菜" .. s.home .. "(荤" .. s.meat .. "/素" .. s.veg .. "/汤" .. s.soup .. ")",
            "外卖" .. s.takeout)
    end
    return ok
end

return M
