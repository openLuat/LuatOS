--[[
@module  theme
@summary 华康生物 · 无菌制剂车间 GMP 环境监控 - 设计令牌（配色 / 版式 / 字号 / 节拍）
@version 1.0
@date    2026.11.11
@board   Air8607 + 10 寸 RGB 屏 1024x600 + GT911 电容触摸

=== 设计取向 ===
洁净车间不是"看产能"的地方，是"看有没有守规矩"的地方：
压差梯度、温湿度、悬浮粒子三件事一旦越界，整批药就是废品。
所以底色压到墨蓝，只有"正在被监控的值"发光：
  冰蓝 = 主强调（压差 / 当前选中）
  薄荷 = 合格 / 正常
  琥珀 = 偏离（接近限值、门未关、滤器阻力高）
  警红 = 超标（压差失守、粒子超限）
一条纪律：合格态只给一条细边和一个小圆点，异常态才整块染色。

=== 坐标体系（1024x600，四周留 12px 安全边）===
  顶栏      y    0 .. 56     车间名 | 系统/A级/超标 | 时钟 | 运行模式胶囊（可点）
  KPI 行    y   62 .. 144     4 块：最低压差 / 平均温度 / 平均湿度 / 环境达标率
  主区      y  152 .. 468     平面图(476) | 温湿度趋势(300) | 事件流(208)
                              AHU 机组条（横跨右侧 516）
  统计条    y  478 .. 554     5 格：A 级房间 / 换气次数 / 高效滤器 / 今日超标 / 能耗
  提示行    y  562 .. 584     操作提示 + 选中房间详情 + 语音开关

=== 字体注意 ===
hzfont 是矢量字库，没有度数（°）、中间点（·）、箭头（→）、上下标这类符号，
用了会显示方框。本工程界面文本只用 ASCII + 汉字 + 斜杠 + 负号 + 百分号，
温度写 "21.4C"、湿度写 "48%RH"、单位写 "Pa" "m3/h" "um"。
]]

local M = {}

-- ==================== 配色 ====================
local c = {
    bg      = 0x070C12,   -- 全屏底色（深墨蓝）
    panel   = 0x0C1520,   -- 卡片底
    panel2  = 0x111E2C,   -- 卡片内嵌块 / 房间底
    line    = 0x1B2E42,   -- 描边
    line2   = 0x2A4763,   -- 亮描边 / 网格
    txt     = 0xE6F0FA,   -- 主文字
    dim     = 0x8FA6BC,   -- 次要文字
    dim2    = 0x51697F,   -- 极弱文字 / 轴标签

    ice     = 0x3FA9F5,   -- 主强调：压差 / 选中
    cyan    = 0x5FE0E8,   -- 亮青：当前时刻 / 曲线首序列
    mint    = 0x34D399,   -- 薄荷：合格 / 正常
    amber   = 0xF5A524,   -- 偏离 / 滤器阻力高
    alarm   = 0xF0526A,   -- 超标 / 压差失守
    violet  = 0x8B7DFF,   -- 湿度 / 第二数据序列

    ink     = 0x03101A,   -- 深色字（压在亮底上时用）
}
M.c = c

M.screen = { w = 1024, h = 600 }

--[[==================== 版式（1024x600 的四条横带）====================
  顶栏      0 .. 56     车间名 / 系统状态 / 时钟 / 运行模式胶囊（全局，可点）
  页面标签  60 .. 104   4 个页签，切页不重建控件，只切隐藏
  内容区   108 .. 552   每页一个容器，几何由各 page_*.lua 自己持有
  提示行   558 .. 582   操作提示 + 挂牌隔离 + 语音开关（全局）

页面内部几何写在各自的 page_*.lua 里：换一页就是换一套版式，
放进 theme 反而会让"哪块归谁"变得说不清。这里只放四页共用的量。
]]
M.top = { y = 0, h = 56 }
M.nav = { y = 60, h = 44, x = 12, w = 176, gap = 6 }
M.body = { y = 108, h = 444 }
M.hint = { y = 558, h = 24 }

-- KPI 条（总览页用）：4 块等宽 244，间距 8，左起 12（12 + 4*244 + 3*8 = 1012）
M.kpi = { x = 12, y = 0, w = 244, h = 76, gap = 8 }

M.f = {
    hero = 32,   -- KPI 主数值
    big  = 26,   -- 房间压差
    num  = 22,   -- 统计条数值
    val  = 15,   -- 房间辅助读数
    body = 16,   -- 正文
    sub  = 14,   -- 表头 / 轴标签
    mini = 12,   -- 极弱说明
}

--[[性能参数
10 寸 RGB 屏没有 GPU，全屏一次就是 61 万像素。四页开机各建一次，切页只 set_hidden；
只有当前页的 update 被调用，每页只重画"真正在变的那块"：
  1 总览  平面 200ms / 待确认 500ms / 概览 700ms / KPI 250ms
  2 气候  监测点 500ms / 趋势 1500ms / 读数卡 300ms
  3 送风  AHU 400ms / 负荷 1000ms / 风路 500ms
  4 事件  事件表 500ms / 统计 500ms
  全局    时钟 250ms / 模式胶囊 500ms
  背景/卡片/标题/页签 开机一次
]]
M.perf = {
    frame_ms = 33,      -- 与 airui 的 33ms 刷新周期对齐
    plan_ms  = 200,     -- 总览页平面图（含门开时的气流动画）
    trend_ms = 1500,    -- 气候页 24h 曲线
    text_ms  = 250,     -- 总览 KPI（内容不变不写）
    demo_speed = 60,    -- 演示时间倍率：1 秒 = 1 分钟，24 分钟走完一天
    point_min = 15,     -- 趋势采样间隔（分钟），96 点 = 24 小时
    auto_sec = 15,      -- 总览页无操作多少秒后开始轮播房间
}

-- ==================== 语音参数 ====================
-- 车间里有风机和层流罩，语音只做"越限回执"，音量压到 18，不抢现场声音。
M.audio = {
    model       = "dac",  -- Air8607：芯片内置 DAC + HT6873 功放
    vol         = 18,     -- 0..100
    pa_ctrl     = 73,     -- 功放使能 AUDIOPA_EN = GPIO73，高电平开
    pa_on_level = 1,
    dac_delay   = 6,
    boot        = true,   -- 开机播一句，值班的人立刻知道语音通路是好的
    boot_text   = "无菌车间环境监控已启动，五间洁净区压差正常",
    auto_gap    = 20,     -- 两条自动播报的最小间隔（秒）
}

return M
