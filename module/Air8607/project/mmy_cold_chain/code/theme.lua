--[[
@module  theme
@summary 冷链温控中枢 - 设计令牌（配色 / 版式 / 字号 / 性能参数）
@version 1.0
@date    2026.11.08
@board   Air8607 + 10 寸 RGB 屏 1024x600（免序列）+ GT911 电容触摸

=== 设计取向 ===
挂在冷库值班室或冷链车间走廊的"温控中枢"：冷库现场光很杂（有人穿棉衣在门口看，
也有人隔着玻璃看），所以对比度优先、颜色少而准：
  冷  = 冰蓝（主强调色，正常态）
  霜  = 青白（除霜 / 低温）
  暖  = 橙（门开 / 接近阈值）
  警  = 红（超温 / 断链风险）
"正常"必须是安静的蓝，"异常"才允许出现红 —— 一块常亮屏如果到处都是红点，
值班的人两天就会开始无视它。

=== 坐标体系（1024x600，四周留 12px 安全边）===
  顶栏      y    0 .. 56     标题 | 三路设备状态 | 时钟 | 运行模式胶囊
  KPI 行    y   62 .. 144     4 块：平均库温 / 压缩机负载 / 今日能耗 / 活动报警
  主区      y  152 .. 468     3 列：温度曲线(384) / 温区矩阵(336) / 事件流(264)
  统计条    y  476 .. 552     5 格：今日能耗 / 峰值负载 / 开门次数 / 超温次数 / 节能率
  提示行    y  560 .. 584     操作提示 + 语音开关

=== 字体注意 ===
hzfont 是矢量字库，没有中间点（·）、度数（°）、箭头（→）这类符号，用了会显示方框。
本工程界面文本只用 ASCII + 汉字 + 斜杠 + 负号，
温度写成 "-18.4C"（摄氏度用字母 C），方向用图元画的箭头表示。
]]

local M = {}

-- ==================== 配色 ====================
local c = {
    bg      = 0x060B12,   -- 全屏底色
    panel   = 0x0C1621,   -- 卡片底
    panel2  = 0x11202D,   -- 卡片内嵌块
    line    = 0x18293A,   -- 描边
    line2   = 0x273D53,   -- 亮描边 / 网格
    txt     = 0xE6F2FB,   -- 主文字
    dim     = 0x8CA4B8,   -- 次要文字
    dim2    = 0x51687C,   -- 极弱文字 / 轴标签

    cold    = 0x3FC8FF,   -- 冷 / 主强调：冰蓝
    frost   = 0x9BE8FF,   -- 除霜 / 霜白青
    warm    = 0xFFA640,   -- 门开 / 接近阈值
    alarm   = 0xFF4D5E,   -- 超温 / 断链
    ok      = 0x33D69F,   -- 正常 / 节能
    pur     = 0x9C7BFF,   -- 第二数据序列

    ink     = 0x04080F,   -- 深色字（压在亮底上时用）
}
M.c = c

M.screen = { w = 1024, h = 600 }

-- ==================== 版式 ====================
M.top = { y = 0, h = 56 }

-- KPI：4 块等宽 244，间距 8，左起 12（12 + 4*244 + 3*8 = 1012，右侧留 12）
M.kpi = { x = 12, y = 62, w = 244, h = 82, gap = 8 }

-- 主区三列
M.curve = { x = 12,  y = 152, w = 384, h = 316 }   -- 24h 温度曲线
M.zones = { x = 404, y = 152, w = 336, h = 316 }   -- 温区矩阵 2x4
M.event = { x = 748, y = 152, w = 264, h = 316 }   -- 事件流

-- 底部统计条：5 格 190 宽，间距 8，左边距 21（居中）
M.stat = { x = 21, y = 476, w = 190, h = 76, gap = 8 }

-- 提示行
M.hint = { y = 560 }

--[[曲线卡片内的绘图区（相对 curve 卡片）
上下留标题(0..34)与图例/轴标签，左右留 Y 轴刻度宽]] 
M.plot = { x = 36, y = 76, w = 332, h = 176 }

--[[温区矩阵（相对 zones 卡片）
2 列 x 4 行：卡内可用 316 宽，padding 10 -> 296；（296-8）/2 = 144
行高：(316 - 34 - 10 - 3*6)/4 = 63]]
M.tile = { x = 10, y = 40, w = 144, h = 63, gapx = 8, gapy = 6 }

-- 事件流行
M.event_row = { x = 8, y = 40, w = 248, h = 30, gap = 4 }

M.f = {
    hero = 40,   -- KPI 主数值
    big  = 28,   -- 卡片主数值
    num  = 22,   -- 统计条数值
    val  = 19,   -- 温区砖块读数
    body = 16,   -- 正文
    sub  = 14,   -- 表头 / 轴标签
    mini = 12,   -- 极弱说明
}

--[[性能参数
10 寸 RGB 屏没有 GPU，全屏一次就是 61 万像素，所以只重画"真正在变的那块"：
  曲线      1Hz（温度是慢变量）
  温区矩阵  500ms（读数 + 呼吸灯）
  事件流    500ms
  KPI 文字  250ms（且内容不变不写）
  背景/卡片 开机一次
]]
M.perf = {
    frame_ms = 33,      -- 与 airui 的 33ms 刷新周期对齐
    tile_ms  = 500,
    event_ms = 500,
    curve_ms = 1000,
    text_ms  = 250,
    demo_speed = 40,    -- 演示时间倍率：1 秒 = 40 秒，36 分钟走完一天
    auto_zone_sec = 12, -- 无人操作时自动轮播温区
}

-- ==================== 语音参数 ====================
-- 走固件本地 TTS（exaudio.play_start type=1），DAC 模式只有一路总音量。
-- 音量取 18：值班室白天有压缩机噪声，但这是"背景播报"，不能盖住人说话。
M.audio = {
    model       = "dac",  -- Air8607：芯片内置 DAC + HT6873 功放
    vol         = 18,     -- 0..100
    priority    = 200,    -- 越高越容易顶掉正在播的那句
    pa_ctrl     = 73,     -- 功放使能 AUDIOPA_EN = GPIO73，高电平开
    pa_on_level = 1,
    dac_delay   = 6,

    boot        = true,   -- 开机播一句，值班的人立刻知道语音通路是好的
    boot_text   = "冷链温控中枢已启动，正在监测八个温区",
    auto_gap    = 10,     -- 两条自动播报的最小间隔（秒）：多路报警不会连珠炮
}

return M
