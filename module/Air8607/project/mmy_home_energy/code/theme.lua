--[[
@module  theme
@summary 家庭能源监测面板 - 设计令牌（配色 / 版式 / 字号 / 性能参数）
@version 1.0
@date    2026.10.26
@board   Air8607 + 10 寸 RGB 屏 1024x600（免序列）+ GT911 电容触摸

=== 设计取向 ===
挂在客厅/配电箱旁边的"能源仪表"：白天要看得清、夜里不能晃眼，
所以底色压到近纯黑，信息只用四个色相区分能量来源：
  光伏 = 暖金  电网 = 蓝  储能 = 紫  家庭负载 = 青绿（主强调色）
"钱"和"碳排放"这类结论性数据用绿色/红色，一眼就知道今天赚了还是亏了。

=== 坐标体系（1024x600，四周留 12px 安全边）===
  顶栏      y    0 .. 56     标题 | 日期时间 | 并网状态 / 刷新指示
  KPI 行    y   62 .. 144    4 块：家庭负载 / 光伏发电 / 电网 / 储能
  主区      y  152 .. 468    3 列：能源流向(336) / 今日曲线(384) / 分路用电(264)
  统计条    y  476 .. 552    5 格：今日用电 / 今日发电 / 自给率 / 今日电费 / 减排
  提示行    y  560 .. 584    操作提示（触摸热区说明）

=== 字体注意 ===
hzfont 是矢量字库，没有中间点（·）、度数（°）、箭头（→）这类符号，
用了会显示方框。本工程界面文本只用 ASCII + 汉字 + 斜杠，
单位写成 "kW" "kWh" "%" "C"，方向用图元画的箭头表示。
]]

local M = {}

-- ==================== 配色 ====================
local c = {
    bg      = 0x070C14,   -- 全屏底色
    panel   = 0x0D1622,   -- 卡片底
    panel2  = 0x121E2D,   -- 卡片内嵌块
    ink     = 0x040810,   -- 深色字（压在亮色底上时用）
    line    = 0x1A2A3C,   -- 描边
    line2   = 0x2A3D53,   -- 亮描边 / 网格
    txt     = 0xE8F1FA,   -- 主文字
    dim     = 0x8FA6BE,   -- 次要文字
    dim2    = 0x54697F,   -- 极弱文字 / 轴标签

    solar   = 0xFFC247,   -- 光伏：暖金
    grid    = 0x4C8DFF,   -- 电网：电光蓝
    batt    = 0x9C7BFF,   -- 储能：紫
    home    = 0x2BE0C8,   -- 家庭负载 / 主强调：青绿

    ok      = 0x3FE08F,   -- 正向（省了钱 / 减排 / 售电）
    warn    = 0xFFB020,   -- 提示（接近阈值）
    red     = 0xFF5A6E,   -- 异常（超载 / 高电价）
    buy     = 0xFF8A5C,   -- 购电（花钱）
}
M.c = c

M.screen = { w = 1024, h = 600 }

-- ==================== 版式 ====================
M.top = { y = 0, h = 56 }

-- KPI 行：4 块等宽 244，间距 8，左起 12（12 + 4*244 + 3*8 = 1012，右侧留 12）
M.kpi = { x = 12, y = 62, w = 244, h = 82, gap = 8 }

-- 主区三列
M.flow  = { x = 12,  y = 152, w = 336, h = 316 }   -- 能源流向
M.chart = { x = 356, y = 152, w = 384, h = 316 }   -- 今日功率曲线
M.circ  = { x = 748, y = 152, w = 264, h = 316 }   -- 分路用电

-- 底部统计条：5 格 190 宽，间距 8，左边距 21（居中）
M.stat = { x = 21, y = 476, w = 190, h = 76, gap = 8 }

-- 提示行
M.hint = { y = 560 }

--[[能源流向图的节点几何（相对 flow 卡片的左上角）
卡片内可用区域 x 0..336 / y 34..268（268 以下留给自己率进度条）：
  光伏(左上 70,88)  储能(右上 266,88)  电网(下中 168,240)  家庭(中心 168,140)
三个来源到家庭的连线互不交叠，动画光点沿着这三条线跑；
家庭节点外圈再套一圈 24 格负荷刻度环（半径 45..50）。
节点半径 25，图标 18~26px；家庭节点半径 38，中心直接放两位数读数。]]
M.node = {
    pv   = { x = 70,  y = 88,  r = 25 },
    batt = { x = 266, y = 88,  r = 25 },
    grid = { x = 168, y = 240, r = 25 },
    home = { x = 168, y = 140, r = 38 },
}

-- 曲线卡片内的绘图区（相对 chart 卡片）
M.plot = { x = 34, y = 74, w = 336, h = 186 }

--[[分路列表（相对 circ 卡片）
8 行 x (32 + 2) = 272，从 y=38 排到 310，正好塞满 316 的卡高。]]
M.circ_row = { x = 12, y = 38, w = 240, h = 32, gap = 2 }

-- 曲线时间轴刻度（小时）
M.axis = { 0, 6, 12, 18, 24 }

M.f = {
    hero = 42,   -- KPI 主数值 / 中央功率
    big  = 28,   -- 卡片主数值
    num  = 22,   -- 统计条数值
    val  = 19,   -- 卡片副值
    body = 16,   -- 正文
    sub  = 14,   -- 表头 / 轴标签
    mini = 12,   -- 极弱说明
}

--[[性能参数
10 寸 RGB 屏没有 GPU，屏幕级重绘一次就是 61 万像素。
把"每帧都在动"的东西压到最小面积：
  - 流向图的动画点：只重画流向卡片内 300x300 的一块；
  - 曲线：1Hz 重画（数据本身就是慢变量）；
  - 分路条：2Hz；
  - KPI 数字：200ms 一次 set_text。
]]
M.perf = {
    frame_ms = 33,      -- 与 airui 的 33ms 刷新周期对齐
    flow_ms  = 66,      -- 流向图 15fps 足够（光点是缓动的）
    chart_ms = 1000,    -- 曲线 1Hz
    circ_ms  = 500,     -- 分路条 2Hz
    text_ms  = 200,     -- 文字节流
    demo_speed = 60,    -- 演示时间倍率：1 秒 = 1 分钟，24 分钟走完一天
    auto_chart_sec = 12 -- 日/周/月视图自动轮换（无人操作时）
}

-- ==================== 语音参数 ====================
-- 走固件本地 TTS（exaudio.play_start type=1），DAC 模式只有一路总音量。
-- 音量取 15：这是一块挂在客厅的常亮面板，报的是背景信息，不抢人。
M.audio = {
    model       = "dac",  -- Air8607：芯片内置 DAC + HT6873 功放
    vol         = 15,     -- 0..100
    priority    = 200,    -- 越高越容易顶掉正在播的那句
    pa_ctrl     = 73,     -- 功放使能 AUDIOPA_EN = GPIO73，高电平开
    pa_on_level = 1,
    dac_delay   = 6,

    boot        = true,   -- 开机播一句，用户立刻知道语音通路是好的
    boot_text   = "能源面板已启动，点一下屏幕上的图标，就能听数据",
    auto_gap    = 8,      -- 两条自动播报的最小间隔（秒）：进峰/进谷不会连着念
}

return M
