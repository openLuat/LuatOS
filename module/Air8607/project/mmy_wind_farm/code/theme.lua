--[[
@module  theme
@summary 北岭风电场集控中枢 - 设计令牌（配色 / 版式 / 字号 / 性能参数）
@version 1.0
@date    2026.11.09
@board   Air8607 + 10 寸 RGB 屏 1024x600（免序列）+ GT911 电容触摸

=== 设计取向 ===
中控室里白天开灯、晚上只留值守灯，屏幕常年不黑。所以底色压到接近黑，
只有"正在发电"的东西才亮：功率曲线、转子、风向玫瑰。
  风  = 青绿（主强调色，在线 / 发电中）
  极光 = 亮青（选中 / 当前时刻）
  琥珀 = 限电 / 降容（调度指令）
  警红 = 故障停机 / 通信中断
  绿   = 正常 / 可用
一条纪律：正常态不要满屏发光，只有异常和"当前时刻"允许跳出底色。

=== 坐标体系（1024x600，四周留 12px 安全边）===
  顶栏      y    0 .. 56     场站名 | 并网/在线/调度 | 时钟 | AGC 胶囊（可点，模拟限电）
  KPI 行    y   62 .. 144     4 块：实时功率 / 平均风速 / 今日发电 / 可用率
  主区      y  152 .. 468     功率曲线(340) | 机组阵列(388) | 风向玫瑰(150)+事件流(158)
  统计条    y  478 .. 554     5 格：今日发电 / 容量系数 / 限电损失 / CO2 减排 / 今日收益
  提示行    y  562 .. 584     操作提示 + 语音开关

=== 字体注意 ===
hzfont 是矢量字库，没有中间点（·）、度数（°）、箭头（→）、上下标这类符号，用了会显示方框。
本工程界面文本只用 ASCII + 汉字 + 斜杠 + 负号 + 百分号，
单位写成 "MW" "MWh" "m/s" "rpm" "C"，方位写成 "N" "NW"。
]]

local M = {}

-- ==================== 配色 ====================
local c = {
    bg      = 0x050A0C,   -- 全屏底色（夜海绿黑）
    panel   = 0x0A1417,   -- 卡片底
    panel2  = 0x0E1E22,   -- 卡片内嵌块
    line    = 0x183034,   -- 描边
    line2   = 0x25474C,   -- 亮描边 / 网格
    txt     = 0xE2F4F1,   -- 主文字
    dim     = 0x8AA6A8,   -- 次要文字
    dim2    = 0x4E6669,   -- 极弱文字 / 轴标签

    wind    = 0x35D6C6,   -- 主强调：风 / 发电中
    aurora  = 0x8BF5E2,   -- 极光青：选中 / 当前时刻
    amber   = 0xFFB04A,   -- 限电 / 降容
    alarm   = 0xFF5468,   -- 故障停机
    ok      = 0x4ADE80,   -- 正常 / 可用
    fcst    = 0x8B7DFF,   -- 预测（第二数据序列）

    ink     = 0x03100F,   -- 深色字（压在亮底上时用）
}
M.c = c

M.screen = { w = 1024, h = 600 }

-- ==================== 版式 ====================
M.top = { y = 0, h = 56 }

-- KPI：4 块等宽 244，间距 8，左起 12（12 + 4*244 + 3*8 = 1012）
M.kpi = { x = 12, y = 62, w = 244, h = 82, gap = 8 }

-- 主区：左功率曲线 / 中机组阵列 / 右（玫瑰 + 事件流）
M.curve = { x = 12,  y = 152, w = 340, h = 316 }
M.farm  = { x = 360, y = 152, w = 388, h = 316 }
M.rose  = { x = 756, y = 152, w = 256, h = 150 }
M.event = { x = 756, y = 310, w = 256, h = 158 }

-- 底部统计条：5 格 190 宽，间距 8，左边距 21（居中）
M.stat = { x = 21, y = 478, w = 190, h = 76, gap = 8 }

M.hint = { y = 562 }

--[[曲线卡片内的绘图区（相对 curve 卡片）
上下留标题(0..34)与图例/轴标签，左侧留 Y 轴刻度]] 
M.plot = { x = 38, y = 84, w = 278, h = 158 }

--[[机组阵列（相对 farm 卡片）
4 列 x 3 行：卡内可用 368 宽，padding 10 -> 368；（368-3*8）/4 = 86
行高：y 从 38 起，3*78 + 2*7 = 248 -> 286，卡片底部 294 留给"选中机组"一行]]
M.tile = { x = 10, y = 38, w = 86, h = 78, gapx = 8, gapy = 7 }

--[[风向玫瑰（相对 rose 卡片 256x150）
圆心放在左侧，右侧 132 起留给"主导风向 / 当前风向"读数。
r=42：圆心 70 加半径 42 就是 112，再留 20 给 E 方位标签，正好不压到右栏]]
M.roseC = { cx = 70, cy = 94, r = 42 }

-- 事件流行（相对 event 卡片）
M.event_row = { x = 8, y = 38, w = 240, h = 25, gap = 3 }

M.f = {
    hero = 32,   -- KPI 主数值
    big  = 26,   -- 卡片主数值
    num  = 22,   -- 统计条数值
    val  = 15,   -- 机组砖块读数
    body = 16,   -- 正文
    sub  = 14,   -- 表头 / 轴标签
    mini = 12,   -- 极弱说明
}

--[[性能参数
10 寸 RGB 屏没有 GPU，全屏一次就是 61 万像素，所以只重画"真正在变的那块"：
  机组阵列  120ms（转子在转，人眼对这个最敏感）
  事件流    500ms
  功率曲线  1s（功率是慢变量）
  KPI 文字  250ms（内容不变不写）
  背景/卡片 开机一次
]]
M.perf = {
    frame_ms = 33,      -- 与 airui 的 33ms 刷新周期对齐
    farm_ms  = 120,     -- 机组阵列（含转子动画）
    event_ms = 500,
    curve_ms = 1000,
    text_ms  = 250,
    demo_speed = 60,    -- 演示时间倍率：1 秒 = 60 秒，24 分钟走完一天
    auto_sec = 12,      -- 无人操作时自动轮播选中机组
}

-- ==================== 语音参数 ====================
-- 中控室有三个人在说话，语音只做"动作回执"，音量压到 16，不抢人声。
M.audio = {
    model       = "dac",  -- Air8607：芯片内置 DAC + HT6873 功放
    vol         = 16,     -- 0..100
    priority    = 200,    -- 越高越容易顶掉正在播的那句
    pa_ctrl     = 73,     -- 功放使能 AUDIOPA_EN = GPIO73，高电平开
    pa_on_level = 1,
    dac_delay   = 6,

    boot        = true,   -- 开机播一句，值班的人立刻知道语音通路是好的
    boot_text   = "北岭风电场集控已启动，十二台机组并网运行",
    auto_gap    = 10,     -- 两条自动播报的最小间隔（秒）
}

return M
