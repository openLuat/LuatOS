--[[
@module  theme
@summary MOTO DASH - 两轮车仪表盘设计令牌（配色 / 几何 / 字号 / 模式）
@version 1.0
@date    2026.10.22
@author  江访

=== 设计取向 ===
汽车/摩托仪表盘的视觉语言是"暗底 + 单一强调色 + 大字号数字"：
夜间骑行时屏幕亮度不能高，所以底色压到接近纯黑，
所有信息靠一个强调色分层，强调色跟随骑行模式变化（节能绿 / 标准青 / 运动橙）。

=== 坐标体系（1024x600）===
  顶栏      y   0 .. 58    左转向 / 大灯 / 时钟 / 远光 / 右转向
  左列卡片  x  24 .. 292   电量（y 84..280）、里程（y 300..496）
  右列卡片  x 732 .. 1000  功率（y 84..280）、速度趋势（y 300..496）
  速度表    圆心 (512,316) 半径 206，指针扫角 150° 到 390°（共 240°）
  底部      y 520 .. 592   三个骑行模式按键

=== 字体注意 ===
hzfont 里没有中间点（·）、度数（°）、约等于（≈）这类符号，用了会显示方框。
本工程所有界面文本只用 ASCII + 汉字 + 斜杠，单位写成 "km/h" "C" 这种纯 ASCII。
]]

local M = {}

-- ==================== 配色 ====================
local c = {
    bg       = 0x05060A,   -- 全屏底色（近纯黑，夜间不刺眼）
    panel    = 0x0F1319,   -- 卡片底
    panel_hl = 0x161C24,   -- 卡片高光层
    line     = 0x212936,   -- 描边
    line2    = 0x2E3949,   -- 亮描边
    dim      = 0x7B879B,   -- 次要文字
    dim2     = 0x414D61,   -- 极弱文字 / 刻度
    txt      = 0xE8EEF7,   -- 主文字

    eco      = 0x2BE59B,   -- 节能：青绿
    normal   = 0x22D3FF,   -- 标准：青蓝
    sport    = 0xFF5A3C,   -- 运动：橙红
    amber    = 0xFFB020,   -- 电量 / 油量
    violet   = 0xA855F7,   -- 温度
    red      = 0xFF3B30,   -- 红线 / 报警
    green    = 0x33E07A,   -- 转向灯
    blue     = 0x4C8DFF,   -- 远光
}
M.c = c

M.screen = { w = 1024, h = 600 }

--[[速度表几何：a0/a1 用"屏幕角度"（0=右，顺时针为正，y 轴向下）
半径必须让整圆落在 y=58 顶栏分隔线与 y=516 底部分隔线之间：
cy + R = 308 + 196 = 504 < 516，上方 308 - 196 = 112 > 58，
两侧 512 ± 196 = 316..708，正好夹在左右卡片（292 / 732）之间。
一开始写成 cy=316 / R=206，圆底压到 522，把底部分隔线穿过去了。
]]
M.dial = {
    cx = 512, cy = 308,
    R  = 196,        -- 最外圈半径
    Ra = 180,        -- 进度弧半径（弧带宽 13）
    a0 = 150, a1 = 390,
    vmax = 160,      -- 表底 160 km/h
    vred = 140,      -- 红线起点
    major = 20,      -- 大刻度间隔（带数字）
    minor = 4,       -- 小刻度间隔
}

M.cards = {
    a = { x = 24,  y = 84,  w = 268, h = 196 },   -- 电量
    b = { x = 24,  y = 300, w = 268, h = 196 },   -- 里程
    c = { x = 732, y = 84,  w = 268, h = 196 },   -- 功率
    d = { x = 732, y = 300, w = 268, h = 196 },   -- 速度趋势
}

-- 骑行模式：名字纯 ASCII，配色与动力学参数一起切换
M.modes = {
    { id = "ECO",    vmax = 60,  acc = 16, dec = 12, color = c.eco },
    { id = "NORMAL", vmax = 110, acc = 30, dec = 18, color = c.normal },
    { id = "SPORT",  vmax = 160, acc = 48, dec = 26, color = c.sport },
}
M.mode_default = 2

-- 底部模式按键
M.chip = { w = 150, h = 44, y = 532, gap = 14 }

M.f = {
    huge = 92,   -- 车速数字
    big  = 42,   -- 卡片主数值
    num  = 26,   -- 里程数值
    val  = 20,   -- 顶栏时钟
    body = 15,
    sub  = 13,
    mini = 11,
}

M.perf = {
    frame_ms = 30,   -- 主循环节拍（与 aurora_ui 一致，30ms 避开 LVGL 33ms 刷新拍频）
    card_ms  = 100,  -- 卡片/仪表条刷新间隔（10Hz，够顺滑又不重排文本）
}

--[[图片素材层
图元负责"精确、可算"的东西（弧、刻度、指针、条），图片负责"柔、有质感"的东西
（底纹、辉光、扫光）。两者叠加才不是"纯代码画出来的塑料感"。

素材打包后就在脚本根 /luadb 下，改 dir 可换加载位置。
三项都可以单独关掉：底纹占一次全屏 blit（1024x600），光晕/扫光是局部小图。]]
M.img = {
    dir  = "/luadb/",
    bg   = true,   -- 碳纤维底纹（全屏静态图）
    glow = true,   -- 手指光晕 + 点击闪光（192px 精灵）
    scan = true,   -- 模式切换扫描光带（1024x96）
}

return M
