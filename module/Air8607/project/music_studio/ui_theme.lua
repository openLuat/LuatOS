--[[
@module  ui_theme
@summary 音乐播放器 - 设计令牌（配色 / 布局 / 字号 / 帧率预算）
@version 1.0
@date    2026.10.23
@board   Air8607 + 10 寸 RGB 屏 1024x600

整屏只认这一份坐标表：ui_main 按 layout 摆控件，ui_styles 按 stage 算画面。
改版面只改这里，不要在 ui_main 里散落硬编码数字。
]]

local M = {}

-- ==================== 配色 ====================
-- 深空蓝底 + 青紫双主色；卡片靠"底色 + 1px 描边"分层（本版 airui 的 shadow 不生效）
M.C = {
    bg      = 0x05070F,   -- 全屏底色
    bg2     = 0x080D19,   -- 舞台/列表底
    card    = 0x0C1322,   -- 卡片底
    card2   = 0x111B2E,   -- 卡片内的次级块（按钮底、列表行）
    card3   = 0x16263F,   -- 选中行底
    line    = 0x1D2A45,   -- 描边
    line2   = 0x2B3D5F,   -- 高亮描边
    text    = 0xE8EFFC,   -- 主文字
    dim     = 0x8B9CB8,   -- 次文字
    dim2    = 0x56668A,   -- 辅助文字
    cyan    = 0x2FE3FF,   -- 主色
    blue    = 0x4A8CFF,
    violet  = 0x9B6BFF,
    pink    = 0xFF5FA8,
    gold    = 0xFFC15A,   -- 警告
    green   = 0x33E3A1,
    ink     = 0x04121C,   -- 亮底上的文字
}

-- ==================== 字号 ====================
-- hzfont 是矢量字库，任意字号都能渲染；但字号种类越多字形缓存越吃紧，控制在 8 档内
M.font = {
    title = 24,   -- 顶栏标题
    h1    = 20,   -- 曲名
    h2    = 17,   -- 按钮主字
    h3    = 15,   -- 小标题
    body  = 14,
    small = 13,
    tiny  = 12,
    micro = 11,
}

-- ==================== 帧率预算 ====================
M.perf = {
    frame_ms = 33,   -- 主循环节拍（约 30fps，与固件 AIRUI_REFRESH_PERIOD_MS 错开）
    ui_ms    = 200,  -- 文字/进度条刷新间隔
    bg_every = 1,    -- 预留：背景层降频倍数
}

-- ==================== 布局（1024x600）====================
--  ┌──────────────────────────────────────────────────────────────┐
--  │ 顶栏 0..56        标题 | 音源与曲目数 | FPS                  │
--  ├──────────┬──────────────────────────┬────────────────────────┤
--  │ 列表     │ 舞台（5 种画面风格）      │ 信息面板               │
--  │ 14..266  │ 278..730                 │ 742..1010              │
--  ├──────────┴──────────────────────────┴────────────────────────┤
--  │ 控制栏 478..586   模式 | 上一曲 播放/暂停 下一曲 | 音量 ±    │
--  └──────────────────────────────────────────────────────────────┘
M.layout = {
    screen_w = 1024,
    screen_h = 600,

    list = { x = 14,  y = 56, w = 252, h = 414 },
    stage = { x = 278, y = 56, w = 452, h = 414 },
    panel = { x = 742, y = 56, w = 268, h = 414 },
    bar   = { x = 14,  y = 478, w = 996, h = 108 },

    stage_pad = 3,    -- 舞台内层内缩（让圆角不被图元溢出的 3px）
    list_rows = 8,    -- 列表可视行数
    row_h = 38,       -- 列表行高（含 2px 间隙）
    row_gap = 2,
    lyric_slots = 7,  -- 歌词同时显示的行数
    lyric_lh = 54,    -- 歌词行距
}

return M
