=== 设计取向 ===
配电房值班大屏：信息密度高但层级必须清楚 ——
  1、底色近纯黑，长时间盯屏不刺眼；
  2、只用一个强调色（电光青）表达主数据，其余靠亮度分层；
  3、状态色（合闸青绿 / 预警暖黄 / 异常红 / 提示蓝紫）只用在真正要判断的地方；
  4、所有卡片同一套圆角、描边、标题格式（竖条 + 中文 + 英文小字）。

=== 版式（1024x600，8px 栅格）===
  顶栏      y    0 .. 56
  左列      x   24 .. 256   主变运行(R1) y 64..296 / 电量需量(R2) y 308..528
  中列      x  276 .. 748   电气主接线 y 64..400 / 三张运行小卡 y 412..528
  右列      x  768 .. 1000  实时告警 y 64..300 / 运行工况 y 312..528
  底栏      y  544 .. 584

=== 字体注意 ===
hzfont 没有中间点（·）、度数（°）这类符号；只用 ASCII + 汉字，
单位写成 "C" "kV" "Hz" "%"，分隔用空格或斜杠。
]]

