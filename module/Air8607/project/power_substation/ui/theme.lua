-- ==================== 节拍 ====================
--[[大屏不需要 30fps：
  - 告警点位 / 潮流亮点要顺一点 -> 每帧（约 16fps）
  - 卡片进度环/条形 -> 500ms
  - 文字 -> 500ms 且只在数值变化时写
每帧真正重绘的只有 2 个 44x44 脉冲点位 + 1 条潮流小条 + 6 个小状态点。]]
