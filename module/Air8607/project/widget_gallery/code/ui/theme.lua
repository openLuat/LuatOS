--[[
@module  theme
@summary WIDGET GALLERY - 大屏组件橱窗设计令牌（配色 / 网格 / 字号 / 分组 / 刷新预算）
@version 1.0
@date    2026.10.23
@author  江访

=== 设计取向 ===
这台 APP 是"组件橱窗"，不是一个业务大屏：它要回答的问题是
「看板上常见的那些部件，用 airui.shape 画出来能有多好看」。
所以视觉上刻意做得中性、克制——深空蓝底、卡片只留一条 1px 描边和一道
顶部高光，让颜色全部由组件本身提供（仪表、曲线、状态灯各自带色相）。
橱窗里最亮的东西永远是"正在变化的那个数"，静态结构一律压到 dim2 以下。

=== 坐标体系（1024x600）===
  顶栏 HUD   y   0 .. 58    标题 | 分组名 + 说明 | FPS / 图元数
  舞台外框   x  12 .. 1012  y  62 .. 514   1000 x 452
  舞台内容   x  15 .. 1009  y  65 .. 511   994 x 446（clip_corner）
  卡片网格   3 列 x 2 行    card 324 x 218   间距 10（横向余 2px 左右各让 1）
  底部切换栏 y 522 .. 588    三个分组按钮 + 自动轮播开关

=== 卡片内部约定 ===
  卡片外框   (x, y, w, h)         w=324 h=218
  标题条     y .. y+30            名称（16px 主字）+ 英文（11px 极弱字，右对齐）
  内容区     y+34 .. y+h-10       高 174，组件画在这里（content() 统一推导）
  卡片内所有图元坐标都由 draw 函数按内容区矩形推导，不写魔法数。

=== 字体注意 ===
hzfont 里没有中间点（·）、度数（°）、乘号（×）、约等于（±/Ω/μ）这类符号，
用了会显示方框。界面文本只用 ASCII + 汉字 + 斜杠：
温度写 "C"、光照写 "klx"、流量写 "m3/h"、频率写 "Hz"、百分号直接 "%"
]]

local M = {}

-- ==================== 配色 ====================
local c = {
    bg       = 0x070A12,   -- 全屏底色
    deep     = 0x090D18,   -- 舞台底色
    panel    = 0x0E1422,   -- 卡片底
    panel_hl = 0x141C2E,   -- 卡片顶部高光带
    line     = 0x243049,   -- 卡片描边
    line2    = 0x33425F,   -- 亮描边 / 刻度
    dim2     = 0x3C4A64,   -- 极弱文字 / 网格暗格
    dim      = 0x7A8AA6,   -- 次要文字
    txt      = 0xE6EDFA,   -- 主文字

    cyan     = 0x22E6FF,
    blue     = 0x4C8DFF,
    violet   = 0xA855F7,
    magenta  = 0xFF3D9A,
    green    = 0x2BE59B,
    lime     = 0xB6FF3C,
    amber    = 0xFFB020,
    orange   = 0xFF7A3C,
    red      = 0xFF4757,
    ink      = 0x04121C,   -- 亮色底上的文字色
}
M.c = c

M.screen = { w = 1024, h = 600 }

-- ==================== 布局 ====================
M.hud   = { h = 58 }
M.stage = { x = 12, y = 62, w = 1000, h = 452 }
-- 内容区（clip_corner 盒子）：外框内缩 3px
M.inner = { x = 15, y = 65, w = 994, h = 446 }

-- 卡片网格：3 x 2
M.card = {
    cols = 3, rows = 2,
    w = 324, h = 218,
    gap = 10,
    ox = 1,    -- 横向总余量 2px，左右各让 1px
    title_h = 30,
    pad = 12,
}
-- 卡片内容区 = content(x,y,w,h) -> (x+12, y+34, w-24, h-44)，324x218 卡得 300x174

M.bar = { y = 522, h = 66 }
M.pill = { x = 26, y = 532, w = 128, h = 46, gap = 10 }
M.auto = { x = 884, y = 532, w = 114, h = 46 }

-- ==================== 字号（与 app_main.lua 载入的字号表一致）====================
M.f = {
    huge  = 64,
    big   = 48,   -- 卡片主数值
    val   = 30,
    title = 26,   -- 顶栏标题（唯一一个非阶梯字号，见 font_sizes）
    body  = 22,
    text  = 16,
    sub   = 13,
    mini  = 11,
}
--[[app_main.lua 按这张表逐个 airui.font_load，界面上用到的字号必须都在里面，
漏了不会报错，只会渲染出方框或回退字形。]]
M.font_sizes = { 11, 13, 16, 22, 26, 30, 48, 64 }

-- ==================== 刷新预算 ====================
M.perf = {
    frame_ms = 30,   -- 主循环节拍（30ms 避开 LVGL 33ms 刷新拍频，同 beat_forge）
    text_ms  = 200,  -- 文字刷新 5Hz：set_text 会让 LVGL 重排文本并产生脏区
    auto_sec = 8,    -- 自动轮播停留时长
}

-- ==================== 分组（三页）====================
--[[
每页 6 张卡片，卡片清单定义在各自的 wg_*.lua 里。
desc 会显示在顶栏 HUD 第二行。
]]
M.groups = {
    { id = "gauge",  name = "仪表", desc = "环形 / 弧形 / 指针 / 刻度 / 液位 / 电量条" },
    { id = "chart",  name = "图表", desc = "面积趋势 / 多路折线 / 柱状 / 火花线 / 热力 / 雷达" },
    { id = "status", name = "状态", desc = "设备矩阵 / 告警列表 / 进度环 / KPI / 步骤条 / 时间轴" },
}
M.group_order = { 1, 2, 3 }

return M
