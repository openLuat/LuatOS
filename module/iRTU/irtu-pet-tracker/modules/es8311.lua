    write_reg(i2c_id, 0x32, 0x00)
    write_reg(i2c_id, 0x17, 0x00)
    write_reg(i2c_id, 0x0E, 0xFF)
    write_reg(i2c_id, 0x12, 0x02)
    write_reg(i2c_id, 0x14, 0x00)
    write_reg(i2c_id, 0x0D, 0xFA)
    write_reg(i2c_id, 0x15, 0x00)
    write_reg(i2c_id, 0x37, 0x08)
    write_reg(i2c_id, 0x02, 0x10)
    write_reg(i2c_id, 0x00, 0x00)
    write_reg(i2c_id, 0x00, 0x1F)
    write_reg(i2c_id, 0x01, 0x30)
    write_reg(i2c_id, 0x01, 0x00)
    write_reg(i2c_id, 0x45, 0x01)
end

