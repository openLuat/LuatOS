  scan_ms   = 40,     -- 扫码线一步（真机改 y，非 CSS 动画）
  scan_step = 3,      -- 每步像素 → 速度 = 3*1000/40 = 75px/s
  poll_ms   = 50,     -- 主循环巡检间隔（有变化才下发）
  -- 切页过渡：新页面从左侧滑入 slide_px 像素（只往左走，右侧绝不越界，见 AGENTS G6）。
  -- 过渡期间主循环临时提到 busy_ms 节拍，否则 50ms 只能出 3 帧，看着就是一跳。
  slide_ms  = 150,    -- 过渡时长
  slide_px  = 48,     -- 位移像素（越大越像推屏，重绘越贵）
  busy_ms   = 16,     -- 过渡期间的主循环节拍（≈60Hz 上限）
}

