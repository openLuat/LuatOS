-- ======================= 节奏 =======================
-- 界面全静态：无持续动画。主循环只做 1Hz 级状态巡检（P10：静止即定格）。
M.ANIM = {
  frame_ms  = 33,     -- 30fps 名义节拍
  press_ms  = 90,     -- 按键下压复原
  fade_ms   = 160,    -- 预留：真机无法做整体淡入（airui 只暴露 bg opa），当前改用 slide_*
