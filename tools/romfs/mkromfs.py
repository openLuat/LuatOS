#!/usr/bin/env python3
# mkromfs.py - 生成标准 romfs(-rom1fs-) 镜像, 供 LuatOS components/romfs 挂载
# 用法:
#   python tools/romfs/mkromfs.py <srcdir> -o out.bin
#   python tools/romfs/mkromfs.py <srcdir> --c-array out.c --name romfs_fixture_img \
#       --hardlink link_hello.txt=hello.txt --symlink sym_hello.txt=hello.txt
#   python tools/romfs/mkromfs.py out.bin --verify
import os, sys, struct, argparse

T_HARD, T_DIR, T_FILE, T_SYM = 0, 1, 2, 3
T_NAME = {0: "hardlink", 1: "dir", 2: "file", 3: "symlink"}


def a16(n):
    return (n + 15) & ~15


class Ent:
    __slots__ = ("name", "type", "children", "data", "target", "off", "next_off")

    def __init__(self, name, type_):
        self.name = name
        self.type = type_
        self.children = []
        self.data = b""
        self.target = None
        self.off = 0
        self.next_off = 0


def build_tree(srcdir, hardlinks, symlinks):
    root = Ent("", T_DIR)

    def add_dir(parent, dpath):
        for fn in sorted(os.listdir(dpath)):
            fp = os.path.join(dpath, fn)
            if os.path.isdir(fp):
                e = Ent(fn, T_DIR)
                parent.children.append(e)
                add_dir(e, fp)
            else:
                e = Ent(fn, T_FILE)
                with open(fp, "rb") as f:
                    e.data = f.read()
                parent.children.append(e)

    add_dir(root, srcdir)

    by_rel = {}

    def index(e, prefix):
        if e.name:
            by_rel[prefix + e.name] = e
        for c in e.children:
            index(c, prefix + (e.name + "/" if e.name else ""))

    index(root, "")
    for spec in hardlinks:  # "link=target", 均相对 srcdir
        link, target = spec.split("=", 1)
        e = Ent(link, T_HARD)
        e.target = by_rel[target]
        root.children.append(e)
    for spec in symlinks:  # "name=target", target 原样写入
        name, target = spec.split("=", 1)
        e = Ent(name, T_SYM)
        e.data = target.encode()
        root.children.append(e)
    return root


def layout(root):
    off = [32]  # 头16 + 空卷名16

    def place(e):
        e.off = off[0]
        sz = 16 + a16(len(e.name.encode()) + 1)
        if e.type in (T_FILE, T_SYM):
            sz += a16(len(e.data))
        off[0] += sz
        for c in e.children:
            place(c)

    place(root)

    def link(children):
        for i, c in enumerate(children):
            c.next_off = children[i + 1].off if i + 1 < len(children) else 0
            link(c.children)

    link(root.children)
    return off[0]


def fix_cksum(buf, off, region_len):
    n = min(512, region_len)
    struct.pack_into(">I", buf, off + 12, 0)  # 先清零再求和
    s = 0
    for i in range(0, (n + 3) & ~3, 4):
        s = (s + struct.unpack(">I", bytes(buf[off + i:off + i + 4]).ljust(4, b"\0"))[0]) & 0xFFFFFFFF
    struct.pack_into(">I", buf, off + 12, (-s) & 0xFFFFFFFF)


def emit(root, total):
    buf = bytearray(total)
    buf[0:8] = b"-rom1fs-"
    struct.pack_into(">I", buf, 8, total)

    def put(e):
        nb = e.name.encode()
        struct.pack_into(">I", buf, e.off, (e.next_off & 0xFFFFFFF0) | e.type)
        if e.type == T_HARD:
            spec = e.target.off
        elif e.type == T_DIR and e.children:
            spec = e.children[0].off
        else:
            spec = 0
        struct.pack_into(">I", buf, e.off + 4, spec)
        struct.pack_into(">I", buf, e.off + 8, len(e.data) if e.type in (T_FILE, T_SYM) else 0)
        buf[e.off + 16:e.off + 16 + len(nb)] = nb
        data_off = e.off + 16 + a16(len(nb) + 1)
        if e.type in (T_FILE, T_SYM):
            buf[data_off:data_off + len(e.data)] = e.data
        fix_cksum(buf, e.off, 16 + a16(len(nb) + 1))
        for c in e.children:
            put(c)

    put(root)
    fix_cksum(buf, 0, total)
    return buf


def verify(path):
    buf = open(path, "rb").read()
    assert buf[0:8] == b"-rom1fs-", "bad magic"
    total = struct.unpack(">I", buf[8:12])[0]
    assert total == len(buf), "size mismatch"

    def walk(off, depth):
        nb = buf[off + 16:off + 16 + a16(256)].split(b"\0", 1)[0].decode()
        w0, spec, size = struct.unpack(">III", buf[off:off + 12])
        print("  " * depth + "%s type=%s size=%d" % (nb or "<root>", T_NAME.get(w0 & 0xF, "?"), size))
        if (w0 & 0xF) == T_DIR and spec:
            walk_children(spec, depth + 1)

    def walk_children(off, depth):
        while off:
            walk(off, depth)
            off = struct.unpack(">I", buf[off:off + 4])[0] & 0xFFFFFFF0

    walk(32, 0)
    print("verify ok, %d bytes" % total)


def write_c_array(buf, path, name, regen_cmd):
    with open(path, "w", newline="\n") as f:
        f.write("// Generated by tools/romfs/mkromfs.py -- DO NOT EDIT\n// regen: %s\n" % regen_cmd)
        f.write("#include <stdint.h>\n\nconst uint8_t %s[] = {\n" % name)
        for i in range(0, len(buf), 12):
            f.write("    " + ", ".join("0x%02X" % b for b in buf[i:i + 12]) + ",\n")
        f.write("};\n\nconst unsigned int %s_len = %d;\n" % (name, len(buf)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("-o", "--output")
    ap.add_argument("--c-array")
    ap.add_argument("--name", default="romfs_img")
    ap.add_argument("--hardlink", action="append", default=[])
    ap.add_argument("--symlink", action="append", default=[])
    ap.add_argument("--verify", action="store_true")
    args = ap.parse_args()
    if args.verify:
        verify(args.src)
        return
    root = build_tree(args.src, args.hardlink, args.symlink)
    buf = emit(root, layout(root))
    if args.output:
        open(args.output, "wb").write(buf)
    if args.c_array:
        write_c_array(buf, args.c_array, args.name,
                      " ".join(["python", "tools/romfs/mkromfs.py"] + sys.argv[1:]))
    print("romfs image: %d bytes" % len(buf))


if __name__ == "__main__":
    main()
